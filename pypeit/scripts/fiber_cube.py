"""
Build datacubes from the spec1d files of fiber-fed or lenslet IFUs.

Generic replacement of the Binospec-specific cube script (which is kept as
a thin alias): the spectrograph supplies the fiber layout through its
fiber hooks (``get_fiber_metadata``, ``load_sky_layout``,
``get_science_fiber_layout_indices``, ``ifu_sky_wcs``) and, through
``fiber_cube_setup``, any state those hooks need (e.g. the Keck/OSIRIS
lenslet layout of the filter) together with default cube parameters.

Optionally, the spectrum of a point source (e.g. a telluric standard) is
extracted by summing the fibers within an aperture and written as a
single-object spec1d file for ``pypeit_sensfunc``/``pypeit_tellfit``.

Generated by JXP and Claude.

.. include:: ../include/links.rst
"""

from __future__ import annotations

import argparse

from pypeit.scripts import scriptbase


class FiberCube(scriptbase.ScriptBase):
    """
    Build a datacube (and optionally a point-source spectrum) from fiber
    spec1d files.

    Generated by JXP and Claude.
    """

    # Spectrograph required by this script (None: any fiber spectrograph)
    required_spectrograph = None
    # Spatial scale (arcsec) when neither the user nor the spectrograph
    # provides one
    default_spatial_scale = 0.27

    @classmethod
    def get_parser(cls, width: int | None = None) -> argparse.ArgumentParser:
        """
        Construct the command-line argument parser.

        Generated by JXP and Claude.

        Args:
            width (:obj:`int`, optional):
                Restrict the width of the formatted help output to be no
                longer than this number of characters.

        Returns:
            `argparse.ArgumentParser`_: Command-line interpreter.
        """
        parser = super().get_parser(
            description='Build a datacube from the spec1d files of a '
                        'fiber-fed or lenslet IFU (Fiber pypeline).',
            width=width, default_log_file=True)
        cls.add_common_arguments(parser)
        parser.add_argument('--spatial_scale', type=float, default=None,
                            help='Output spatial pixel scale in arcsec '
                                 '(default: provided by the spectrograph, '
                                 f'else {cls.default_spatial_scale})')
        parser.add_argument('--point_source', type=float, default=None,
                            help='Also extract a point source: sum the '
                                 'fibers within this radius (arcsec) of '
                                 'the brightest source and write a '
                                 'single-object spec1d file (*_ps.fits) '
                                 'for pypeit_sensfunc/pypeit_tellfit')
        parser.add_argument('--no_cube', default=False, action='store_true',
                            help='Do not build the datacube (e.g. with '
                                 '--point_source only)')
        return parser

    @classmethod
    def add_common_arguments(cls, parser):
        """
        Arguments shared with the Binospec alias.

        Generated by JXP and Claude.

        Args:
            parser (`argparse.ArgumentParser`_):
                Parser to which the arguments are added.
        """
        parser.add_argument('files', type=str, nargs='+',
                            help='One or more PypeIt spec1d files, or a text '
                                 'file listing them (one per line)')
        parser.add_argument('-o', '--output', type=str, default=None,
                            help='Output FITS filename (only valid for a '
                                 'single input file; default: '
                                 'auto-generated)')
        parser.add_argument('--boxcar', default=False, action='store_true',
                            help='Use boxcar (BOX) extraction columns instead '
                                 'of the default optimal (OPT) columns (the '
                                 'boxcar is used anyway when the file has no '
                                 'optimal extraction)')
        parser.add_argument('--method', type=str, default='linear',
                            choices=['nearest', 'linear', 'cubic'],
                            help='Spatial interpolation method (default: '
                                 'linear)')

    @staticmethod
    def input_files(files):
        """
        Expand the list of input files (text files list spec1d files).

        Generated by JXP and Claude.

        Args:
            files (:obj:`list`):
                Command-line file arguments.

        Returns:
            :obj:`list`: The spec1d files.
        """
        from pathlib import Path
        from pypeit import PypeItError
        out = []
        for f in files:
            if f.endswith('.txt'):
                for line in Path(f).read_text().splitlines():
                    line = line.strip()
                    if line and not line.startswith('#'):
                        out.append(line)
            else:
                out.append(f)
        if len(out) == 0:
            raise PypeItError('No input files provided.')
        for f in out:
            if not Path(f).name.startswith('spec1d'):
                raise PypeItError(
                    f'Only spec1d files are supported; got {Path(f).name}')
        return out

    @classmethod
    def main(cls, args: argparse.Namespace) -> None:
        """
        Build the datacubes (and point-source spectra).

        Generated by JXP and Claude.

        Args:
            args (`argparse.Namespace`_):
                Parsed command-line arguments.
        """
        from pathlib import Path

        from astropy.io import fits

        from pypeit import log, PypeItError
        from pypeit.core import datacube
        from pypeit.spectrographs.util import load_spectrograph

        cls.init_log(args)
        files = cls.input_files(args.files)
        if args.output is not None and len(files) > 1:
            raise PypeItError('--output can only be used with a single '
                              'input file.')
        log.info(f'Processing {len(files)} spec1d file(s)')

        point_source = getattr(args, 'point_source', None)
        no_cube = getattr(args, 'no_cube', False)
        for input_file in files:
            hdr = fits.getheader(input_file)
            spectrograph = load_spectrograph(hdr['PYP_SPEC'])
            if cls.required_spectrograph is not None \
                    and spectrograph.name != cls.required_spectrograph:
                raise PypeItError(
                    f'This script requires a {cls.required_spectrograph} '
                    f'spec1d; got PYP_SPEC={spectrograph.name!r}')
            if spectrograph.pypeline != 'Fiber':
                raise PypeItError(f'{spectrograph.name} is not reduced with '
                                  'the Fiber pypeline.')
            # Spectrograph state needed by the fiber hooks, and its cube
            # defaults (e.g. Keck/OSIRIS: lenslet layout of the filter)
            defaults = spectrograph.fiber_cube_setup(hdr)
            scale = args.spatial_scale
            if scale is None:
                scale = defaults.get('spatial_scale',
                                     cls.default_spatial_scale)
            wcs_ref = defaults.get('wcs_ref', 'center')
            targetx, targety = spectrograph.load_sky_layout()

            if not no_cube:
                log.info(f'Building datacube for {Path(input_file).name} '
                         f'(spatial scale {scale} arcsec)')
                datacube.build_cube_from_spec1d(
                    input_file, spectrograph, targetx, targety,
                    boxcar=args.boxcar, spatial_scale=scale,
                    method=args.method, output=args.output, wcs_ref=wcs_ref)
            if point_source is not None:
                datacube.extract_fiber_point_source(
                    input_file, spectrograph, targetx, targety,
                    point_source, boxcar=args.boxcar)
