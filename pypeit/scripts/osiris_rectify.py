"""
Rectify (extract the lenslet spectra of) a raw Keck/OSIRIS frame.

Development tool for the OSIRIS port: it runs the lenslet rectification of
:mod:`pypeit.core.lenslet_rectify` on a raw frame (optionally minus a
second, background frame) and writes the rectified image, its inverse
variance and mask.  It is not part of the main reduction flow.

.. include common links, assuming primary doc root is up one directory
.. include:: ../include/links.rst
"""
import time
from pathlib import Path

import numpy as np

from astropy.io import fits

from pypeit import log
from pypeit import PypeItError
from pypeit.core import lenslet_rectify
from pypeit.scripts import scriptbase
from pypeit.spectrographs.util import load_spectrograph


class OsirisRectify(scriptbase.ScriptBase):
    """
    Script to rectify a raw Keck/OSIRIS frame with a Keck rectification
    matrix.

    Generated by JXP and Claude.
    """

    @classmethod
    def get_parser(cls, width=None):
        """
        Construct the command-line argument parser.

        Generated by JXP and Claude.

        Args:
            width (:obj:`int`, optional):
                Restrict the width of the formatted help output.

        Returns:
            `argparse.ArgumentParser`_: The parser.
        """
        parser = super().get_parser(
            description='Rectify a raw Keck/OSIRIS frame (optionally minus a '
                        'background frame) with a Keck rectification matrix, '
                        'producing one row per lenslet slice.  Output: a '
                        'FITS file with the rectified image (ADU), its '
                        'inverse variance and mask (1 = bad), with shape '
                        '(2048 detector columns, nslice) in the raw column '
                        'order, and the raw header.', width=width)
        parser.add_argument('raw_file', type=str,
                            help='Raw OSIRIS frame (H2RG era, >= 2016)')
        parser.add_argument('--bkg', type=str, default=None,
                            help='Raw background frame subtracted from '
                                 'raw_file before rectification (A-B)')
        parser.add_argument('-m', '--matrix', type=str, required=True,
                            help='Rectification matrix file, or a directory '
                                 'of matrices from which the matrix is '
                                 'selected by filter, scale and date')
        parser.add_argument('--method', type=str, default=None,
                            choices=['drp', 'lstsq'],
                            help='Solver; default from the '
                                 'osiris_rect_method parameter (lstsq)')
        parser.add_argument('--niter', type=int, default=None,
                            help='Iterations of the drp solver; default '
                                 'from osiris_rect_niter (40)')
        parser.add_argument('--relax', type=float, default=None,
                            help='Relaxation of the drp solver; default '
                                 'from osiris_rect_relax (1.0)')
        parser.add_argument('--use_var', default=False, action='store_true',
                            help='Use the VAR extension(s) for the pixel '
                                 'noise instead of the PypeIt noise model '
                                 '(gain, read noise and shot noise)')
        parser.add_argument('--no_refrows', default=False,
                            action='store_true',
                            help='Do not subtract the per-column median of '
                                 'the unilluminated rows 2032-2044 (DRP '
                                 '"Adjust Channel Levels" for the H2RG)')
        parser.add_argument('--no_bpm', default=False, action='store_true',
                            help='Do not mask the Keck hot/dead pixels and '
                                 'the DQ != 9 pixels')
        parser.add_argument('-o', '--outfile', type=str, default=None,
                            help='Output file; default '
                                 '<raw_file stem>_rect.fits in the current '
                                 'directory')
        parser.add_argument('--overwrite', default=False,
                            action='store_true',
                            help='Overwrite an existing output file')
        return parser

    @staticmethod
    def read_frame(spec, filename):
        """
        Read a raw OSIRIS frame in the raw orientation.

        Generated by JXP and Claude.

        Args:
            spec (``KeckOSIRISSpectrograph``):
                Spectrograph object (``keck_osiris``).
            filename (:obj:`str`):
                Raw file.

        Returns:
            :obj:`tuple`: Image (ADU), variance (ADU^2; PypeIt model, or
            from ``VAR`` when requested later), bad-pixel mask (from DQ),
            exposure time (s), primary header, detector parameters and
            the ``VAR`` extension converted to ADU^2 (or None).
        """
        detpar, img, hdu, exptime, _, _ = spec.get_rawimage(filename, 1)
        var_ext, dq = spec.read_var_dq(hdu)
        hdr = hdu[0].header.copy()
        hdu.close()
        bpm = np.zeros(img.shape, dtype=bool) if dq is None else dq != 9
        # PypeIt noise model in ADU^2: shot noise + read noise
        gain = float(detpar['gain'][0])
        rn = float(detpar['ronoise'][0])
        var = np.clip(img, 0., None) / gain + (rn / gain)**2
        # VAR is the variance of the ADU/s/coadd image
        var_adu = None if var_ext is None \
            else np.asarray(var_ext, dtype=float) * exptime**2
        return img, var, bpm, exptime, hdr, detpar, var_adu

    @staticmethod
    def main(args):
        """
        Execute the script.

        Generated by JXP and Claude.

        Args:
            args (`argparse.Namespace`_):
                Parsed command-line arguments.
        """
        spec = load_spectrograph('keck_osiris')
        cpar = spec.default_pypeit_par()['calibrations']
        method = cpar['osiris_rect_method'] if args.method is None \
            else args.method
        niter = cpar['osiris_rect_niter'] if args.niter is None \
            else args.niter
        relax = cpar['osiris_rect_relax'] if args.relax is None \
            else args.relax
        use_var = cpar['osiris_rect_use_var'] or args.use_var

        outfile = Path(f'{Path(args.raw_file).name.split(".fits")[0]}'
                       '_rect.fits') if args.outfile is None \
            else Path(args.outfile)
        if outfile.exists() and not args.overwrite:
            raise PypeItError(f'{outfile} exists; use --overwrite.')

        # Raw frame(s), in the raw orientation and ADU
        img, var, bpm, exptime, hdr, detpar, var_ext = \
            OsirisRectify.read_frame(spec, args.raw_file)
        if use_var:
            if var_ext is None:
                raise PypeItError(f'{args.raw_file} has no VAR extension.')
            var = var_ext
        # Flux-independent weighting variance (read noise + smooth
        # background; M2 Q&A 1), in ADU^2
        rn_var = (float(detpar['ronoise'][0]) / float(detpar['gain'][0]))**2
        gain = float(detpar['gain'][0])
        wvar = lenslet_rectify.background_variance(img * gain, rn_var * gain**2,
                                                   bpm) / gain**2
        if args.bkg is not None:
            bimg, bvar, bbpm, bexp, _, _, bvar_ext = \
                OsirisRectify.read_frame(spec, args.bkg)
            if not np.isclose(bexp, exptime):
                log.warning(f'Exposure times differ ({exptime} vs {bexp} '
                            's); subtracting the frames in ADU anyway.')
            wvar = wvar + lenslet_rectify.background_variance(
                bimg * gain, rn_var * gain**2, bbpm) / gain**2
            img = img - bimg
            var = var + (bvar_ext if use_var else bvar)
            bpm |= bbpm
        # Column offsets from the unilluminated reference rows; for an A-B
        # pair this is applied to the difference, as in the DRP that made
        # the reference cubes (the PypeIt flow applies it to each frame)
        if not args.no_refrows:
            img = lenslet_rectify.subtract_reference_rows(img)
        if not args.no_bpm:
            hot, dead = spec.load_static_masks()
            bpm |= hot | dead
        else:
            bpm[...] = False

        # Matrix
        mpath = Path(args.matrix).expanduser()
        if mpath.is_dir():
            mpath = lenslet_rectify.select_matrix(
                mpath, hdr['SFILTER'], hdr['SSCALE'], hdr['MJD-OBS'])
        matrix = lenslet_rectify.RectMatrix.from_file(mpath)

        # Solve
        log.info(f'Rectifying {args.raw_file} with method={method}')
        t0 = time.perf_counter()
        weights = np.where(wvar > 0, 1. / np.where(wvar > 0, wvar, 1.), 0.)
        if method == 'drp':
            rect, _, rbpm = lenslet_rectify.rectify_drp(
                img, bpm, matrix, niter=niter, relax=relax)
            # Variance from the least-squares machinery (M2 Q&A 3)
            (var_out,), vbpm = lenslet_rectify.lstsq_variance(
                weights, bpm, matrix, [var])
            ivar = np.where(var_out > 0, 1. / np.where(var_out > 0,
                                                        var_out, 1.), 0.)
            rbpm = rbpm | vbpm
        else:
            # Flux-independent weights and sandwich variance (M2 Q&A 1)
            rect, ivar, rbpm = lenslet_rectify.rectify_lstsq(
                img, weights, bpm, matrix, var=var)
        dt = time.perf_counter() - t0
        log.info(f'Rectification took {dt:.1f} s')

        # Output
        # The raw primary header is named SCI; the output primary is empty
        hdr.remove('EXTNAME', ignore_missing=True)
        hdr['RECTMETH'] = (method, 'OSIRIS rectification method')
        hdr['RECTMAT'] = (mpath.name, 'Rectification matrix')
        hdr['RECTNIT'] = (niter, 'drp iterations')
        hdr['RECTRLX'] = (relax, 'drp relaxation')
        hdr['RECTVAR'] = (use_var, 'Noise from the VAR extension')
        hdr['RECTBKG'] = ('None' if args.bkg is None
                          else Path(args.bkg).name, 'Background frame')
        hdr['RECTREF'] = (not args.no_refrows, 'Ref-row column offsets '
                          'removed')
        hdr['RECTTIME'] = (round(dt, 2), 'Rectification time (s)')
        hdr['EXPTIME'] = (exptime, 'Exposure time (s)')
        hdr['BUNIT'] = 'ADU'
        hdr['HISTORY'] = ('pypeit_osiris_rectify: axis 1 (NAXIS2) is the '
                          'raw detector column, axis 2 (NAXIS1) the slice')
        hdus = [fits.PrimaryHDU(header=hdr),
                fits.ImageHDU(rect.astype(np.float32), name='RECT'),
                fits.ImageHDU(np.zeros(rect.shape, dtype=np.float32)
                              if ivar is None else ivar, name='IVAR'),
                fits.ImageHDU(rbpm.astype(np.uint8), name='MASK')]
        fits.HDUList(hdus).writeto(outfile, overwrite=args.overwrite)
        log.info(f'Wrote {outfile}')
