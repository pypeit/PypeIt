"""
The Dashboard status/activity area (design X4/X5).

A status bar — distinct from the PypeIt reduction *state* — that reports what
the *Dashboard* is doing and when it is waiting on a task (launching a viewer,
computing/reloading state, idle), with a busy indicator for long operations.
It is shared by both tabs.

Generated by JXP and Claude.
"""

from qtpy.QtWidgets import QStatusBar, QLabel, QProgressBar


class ActivityBar(QStatusBar):
    """
    The shared Dashboard status/activity bar (X4/X5).

    Generated by JXP and Claude.

    Args:
        parent (:obj:`QWidget`, optional):
            The parent widget.
    """

    def __init__(self, parent=None):
        super().__init__(parent=parent)
        # A fixed title, then the message label (left), then an indeterminate
        # busy bar (right) hidden until a long/blocking task is running.
        title = QLabel('Dashboard status:')
        title.setStyleSheet('font-weight: bold;')
        self.addWidget(title)
        self._message = QLabel('Idle')
        self.addWidget(self._message, stretch=1)
        self._busy = QProgressBar()
        self._busy.setRange(0, 0)        # range (0,0) → indeterminate spinner
        self._busy.setMaximumWidth(140)
        self._busy.setVisible(False)
        self.addPermanentWidget(self._busy)

    def set_status(self, message, busy=False):
        """
        Show an activity message, optionally with the busy indicator.

        Generated by JXP and Claude.

        Args:
            message (:obj:`str`): The message to display.
            busy (:obj:`bool`, optional): Show the busy indicator.

        Returns:
            None.
        """
        self._message.setText(message)
        self._busy.setVisible(busy)

    def idle(self):
        """
        Reset the bar to the idle state.

        Generated by JXP and Claude.

        Returns:
            None.
        """
        self.set_status('Idle', busy=False)

    def message(self):
        """
        Return the current message text (used by tests).

        Generated by JXP and Claude.

        Returns:
            str: The current message.
        """
        return self._message.text()
