"""
A simple full-view dialog for a QA PNG (design C9).

Per the Stage 3 decision (S3-Q6) this is a basic image window — a scrollable
``QLabel``/``QPixmap`` — sufficient to open a QA figure at full size.

Generated by JXP and Claude.
"""

from pathlib import Path

from qtpy.QtWidgets import (QDialog, QVBoxLayout, QLabel, QScrollArea)
from qtpy.QtCore import Qt
from qtpy.QtGui import QPixmap


class QaImageDialog(QDialog):
    """
    A modeless dialog showing a single QA PNG at full size.

    Generated by JXP and Claude.

    Args:
        png_path (:obj:`str`, `pathlib.Path`_):
            Path to the QA PNG.
        parent (:obj:`QWidget`, optional):
            The parent widget.
    """

    def __init__(self, png_path, parent=None):
        super().__init__(parent=parent)
        self.setWindowTitle(Path(png_path).name)

        layout = QVBoxLayout(self)
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        label = QLabel()
        label.setAlignment(Qt.AlignCenter)
        pixmap = QPixmap(str(png_path))
        if pixmap.isNull():
            label.setText(f'Could not load image:\n{png_path}')
        else:
            label.setPixmap(pixmap)
        scroll.setWidget(label)
        layout.addWidget(scroll)
        self.resize(900, 700)
