"""
Module for Keck/OSIRIS specific methods.

OSIRIS is the Keck I adaptive-optics near-infrared lenslet integral-field
spectrograph.  Its raw frames contain up to ~3000 interleaved lenslet
spectra spaced only 2 pixels apart; they are separated with the Keck
rectification matrices before the ``Fiber`` pypeline takes over (see the
design document in the PypeIt development suite,
``pypeitdev/keck_osiris/keck_osiris_design.md``).

This module currently implements the spectrograph skeleton: metadata,
frame typing, detector parameters, raw-image reading, the bad-pixel mask,
the default parameters, and loaders for the static Keck calibration files
shipped with PypeIt.  Only data taken with the H2RG spectrograph detector
(on or after 2016-01-01) are supported.

.. include:: ../include/links.rst
"""
import re
from pathlib import Path

import numpy as np

from astropy.io import fits
from astropy.table import Table

from pypeit import dataPaths
from pypeit import io
from pypeit import log
from pypeit import PypeItError
from pypeit import telescopes
from pypeit import utils
from pypeit.core import framematch
from pypeit.images import detector_container
from pypeit.par import parset
from pypeit.pkg.pypeitdata import PypeItDataPath
from pypeit.spectrographs import spectrograph


class KeckOSIRISSpectrograph(spectrograph.Spectrograph):
    """
    Child to handle Keck/OSIRIS (lenslet IFU spectrograph) specific code.

    Generated by JXP and Claude.
    """
    ndet = 1
    name = 'keck_osiris'
    telescope = telescopes.KeckTelescopePar()
    camera = 'OSIRIS'
    # Label only; PypeIt never matches files to spectrographs by this name
    header_name = 'OSIRIS'
    url = 'https://www2.keck.hawaii.edu/inst/osiris/'
    pypeline = 'Fiber'
    # Not supported until a dev-suite reduction test passes
    supported = False
    comment = ('Lenslet IFU; H2RG era (>= 2016) only; requires Keck '
               'rectification matrices')

    # Geometry constants (OSIRIS manual App. E; verified on data in
    # Report 01 of the development suite)
    NSLICE_BB = 1216
    """Number of slices stored in a rectification matrix (19 x 64)."""
    NROW_BAND = 32
    """Detector rows per lenslet-column band."""
    MJD_H2RG = 57388.0
    """MJD of 2016-01-01, when the H2RG spectrograph detector came online."""
    TEMP_REF_WAVE = 50.73
    """TMA temperature (K) of the reference wavelength solution (DRP)."""

    # Read noise (e-) of the H2RG versus the number of MCDS read pairs,
    # from the Keck OSIRIS specifications page; NUMREADS=1 is plain CDS.
    MCDS_NREADS = np.array([1., 4., 16., 32.])
    MCDS_RN = np.array([22.0, 12.2, 8.1, 7.8])
    UTR_RN = 8.0

    # Regular expressions identifying a telluric/flux standard from its
    # target name.  OBSTYPE is 'a' for every on-sky frame in the KOA data
    # (even for the A0V stars), so the name is the only usable handle.
    STD_SPTYPE_RE = re.compile(r'\(\s*[OBAFGKM]\d(\.\d)?\s*(I|II|III|IV|V)'
                               r'[ab]?\s*\)', re.IGNORECASE)
    STD_CATALOG_RE = re.compile(r'^\s*(HD|HIP|HR|BD|SAO|TYC|FS|GD|HZ|FEIGE|'
                                r'LTT|EG)[\s_-]*[+-]?\d', re.IGNORECASE)
    STD_MAX_EXPTIME = 60.0
    """Maximum exposure time (s) for a catalogue-named star to be a standard."""

    def init_meta(self):
        """
        Define how metadata are derived from the spectrograph files.

        That is, this associates the PypeIt-specific metadata keywords
        with the instrument-specific header cards using :attr:`meta`.

        Generated by JXP and Claude.
        """
        self.meta = {}
        # Required (core)
        self.meta['ra'] = dict(ext=0, card='RA')
        self.meta['dec'] = dict(ext=0, card='DEC')
        # OBJECT is often empty; TARGNAME is reliable
        self.meta['target'] = dict(ext=0, card='TARGNAME')
        self.meta['dispname'] = dict(ext=0, card='SFILTER')
        # Plate scale ('0.020', '0.035', '0.050', '0.100'), kept as a string
        self.meta['decker'] = dict(ext=0, card='SSCALE')
        self.meta['binning'] = dict(ext=0, card=None, default='1,1')
        self.meta['mjd'] = dict(ext=0, card='MJD-OBS')
        self.meta['exptime'] = dict(card=None, compound=True)
        self.meta['airmass'] = dict(ext=0, card='AIRMASS')

        # Extras for configuration, frame typing and bookkeeping
        self.meta['idname'] = dict(card=None, compound=True)
        self.meta['issky'] = dict(card=None, compound=True)
        self.meta['instrument'] = dict(card=None, compound=True)
        self.meta['posang'] = dict(card=None, compound=True)
        self.meta['ra_off'] = dict(ext=0, card='RAOFF', required=False)
        self.meta['dec_off'] = dict(ext=0, card='DECOFF', required=False)
        self.meta['sampmode'] = dict(ext=0, card='SAMPMODE', required=False)
        self.meta['numreads'] = dict(ext=0, card='NUMREADS', required=False)
        # TMA temperature; drives the DRP grating-expansion correction
        self.meta['tmatemp'] = dict(ext=0, card='DTMP7', required=False)

        # IFU subheader keys (needed by Spectrograph.subheader_for_spec)
        self.meta['slitwid'] = dict(card=None, compound=True)
        self.meta['pressure'] = dict(card=None, compound=True,
                                     required=False)
        self.meta['temperature'] = dict(card=None, compound=True,
                                        required=False)
        self.meta['humidity'] = dict(card=None, compound=True,
                                     required=False)
        self.meta['parangle'] = dict(card=None, compound=True,
                                     required=False)

    def compound_meta(self, headarr, meta_key):
        """
        Methods to generate metadata requiring interpretation of the header
        data, instead of simply reading the value of a header card.

        Generated by JXP and Claude.

        Args:
            headarr (:obj:`list`):
                List of `astropy.io.fits.Header`_ objects.
            meta_key (:obj:`str`):
                Metadata keyword to construct.

        Returns:
            object: Metadata value read from the header(s).
        """
        hdr = headarr[0]
        if meta_key == 'exptime':
            return self.exptime_from_header(hdr)
        if meta_key == 'idname':
            # OBSTYPE is 'astro'/'star'/'calib' (2015) or 'a'/'s'/'c' (2016+)
            return str(hdr.get('OBSTYPE', '')).strip()[:1].lower()
        if meta_key == 'issky':
            # ISSKY is missing from truncated headers; default to 0
            try:
                return int(hdr.get('ISSKY', 0))
            except (TypeError, ValueError):
                return 0
        if meta_key == 'instrument':
            # INSTRUME is absent before 2017; CURRINST names the instrument
            # selected at the telescope (e.g. 'LRISADC' during daytime
            # darks), so it is only the fallback.
            for card in ['INSTRUME', 'CURRINST']:
                if card in hdr and str(hdr[card]).strip() != '':
                    return str(hdr[card]).strip()
            return 'OSIRIS'
        if meta_key == 'posang':
            # Sky position angle of the IFU from the rotator (PA_SPEC is
            # missing from truncated headers):  ROTPOSN - INSTANGL + ROTREFAN
            rotposn = hdr.get('ROTPOSN', 0.)
            instangl = hdr.get('INSTANGL', 0.)
            rotrefan = hdr.get('ROTREFAN', 0.)
            return float(rotposn - instangl + rotrefan) % 360.
        if meta_key == 'slitwid':
            # Lenslet size on the sky in degrees (used for the IFU WCS)
            return self.platescale_from_header(hdr) / 3600.
        if meta_key == 'pressure':
            try:
                return hdr['WXPRESS']  # mbar
            except KeyError:
                log.warning('Pressure is not in header; assuming the '
                            'Maunakea default of 611 mbar')
                return 611.0
        if meta_key == 'temperature':
            try:
                return hdr['WXOUTTMP']  # deg C
            except KeyError:
                log.warning('Temperature is not in header; assuming the '
                            'Maunakea default of 1.5 deg C')
                return 1.5  # van Kooten & Izett, arXiv:2208.11794
        if meta_key == 'humidity':
            try:
                return hdr['WXOUTHUM']  # percent
            except KeyError:
                log.warning('Humidity is not in header; assuming the '
                            'Maunakea default of 20 %')
                return 20.0  # van Kooten & Izett, arXiv:2208.11794
        if meta_key == 'parangle':
            try:
                # Parallactic angle in radians
                return np.deg2rad(hdr['PARANG'])
            except KeyError:
                log.warning('Parallactic angle is not in header; '
                            'assuming 0')
                return 0.0
        raise PypeItError(f'Not ready for compound meta {meta_key} for '
                          f'{self.name}')

    @classmethod
    def exptime_from_header(cls, hdr):
        """
        Compute the total exposure time (s) from a raw OSIRIS header.

        The exposure time is ``ITIME x COADDS``.  ``ITIME`` is recorded in
        seconds before the 2016 detector upgrade and in milliseconds
        afterwards.  The era is decided from ``MJD-OBS`` when it is
        available; otherwise ``ITIME > 2000`` flags milliseconds.
        ``TRUITIME`` is not used (it is absent before 2017).

        Generated by JXP and Claude.

        Args:
            hdr (`astropy.io.fits.Header`_ or :obj:`dict`):
                Primary header of the raw frame.

        Returns:
            :obj:`float`: Total exposure time in seconds.
        """
        itime = float(hdr['ITIME'])
        coadds = int(hdr.get('COADDS', 1))
        mjd = hdr.get('MJD-OBS', None)
        try:
            in_ms = float(mjd) >= cls.MJD_H2RG
        except (TypeError, ValueError):
            # No usable MJD: fall back to the size of the number
            in_ms = itime > 2000.
        if in_ms:
            itime /= 1000.
        return itime * coadds

    @staticmethod
    def platescale_from_header(hdr, default=0.05):
        """
        Parse the lenslet scale (arcsec) from the ``SSCALE`` header card.

        Generated by JXP and Claude.

        Args:
            hdr (`astropy.io.fits.Header`_ or :obj:`dict`):
                Primary header of the raw frame.
            default (:obj:`float`, optional):
                Value returned when ``SSCALE`` is missing or unparsable.

        Returns:
            :obj:`float`: Lenslet scale in arcsec.
        """
        try:
            return float(str(hdr['SSCALE']).strip())
        except (KeyError, ValueError):
            log.warning(f'Could not parse SSCALE; assuming {default} arcsec')
            return default

    def configuration_keys(self):
        """
        Return the metadata keys that define a unique instrument
        configuration (filter and lenslet scale).

        Generated by JXP and Claude.

        Returns:
            :obj:`list`: List of keywords of data pulled from file headers
            and used to constuct the :class:`~pypeit.metadata.PypeItMetaData`
            object.
        """
        return ['dispname', 'decker']

    def raw_header_cards(self):
        """
        Return additional raw header cards to be propagated in
        downstream output files for configuration identification.

        Generated by JXP and Claude.

        Returns:
            :obj:`list`: List of keywords from the raw data files that should
            be propagated in output files.
        """
        return ['SFILTER', 'SSCALE', 'SAMPMODE', 'NUMREADS', 'ITIME',
                'COADDS', 'ROTPOSN', 'INSTANGL']

    def pypeit_file_keys(self):
        """
        Define the list of keys to be output into a standard PypeIt file.

        The ``comb_id``/``bkg_id`` columns are included so the user can set
        the A-B (object-sky) pairing by hand; it cannot be derived reliably
        from the headers.

        Generated by JXP and Claude.

        Returns:
            :obj:`list`: The list of keywords in the relevant
            :class:`~pypeit.metadata.PypeItMetaData` instance to print to the
            :ref:`pypeit_file`.
        """
        return super().pypeit_file_keys() \
                + ['issky', 'idname', 'calib', 'comb_id', 'bkg_id']

    def is_standard_target(self, target, exptime):
        """
        Identify telluric/flux standard stars from their target names.

        OSIRIS writes ``OBSTYPE = 'a'`` for every on-sky frame (including
        the A0V stars in the KOA data), so standards are recognised by a
        spectral-type tag in the name (e.g. ``HD101060(A0V)``) or by a
        bright-star catalogue name (HD, HIP, HR, ...) observed with a short
        exposure.

        Generated by JXP and Claude.

        Args:
            target (array-like):
                Target names.
            exptime (array-like):
                Exposure times in seconds.

        Returns:
            `numpy.ndarray`_: Boolean array, True for likely standards.
        """
        names = np.atleast_1d(np.asarray(target, dtype=str))
        texp = np.atleast_1d(np.asarray(exptime, dtype=float))
        has_sptype = np.array([self.STD_SPTYPE_RE.search(n) is not None
                               for n in names])
        is_catalog = np.array([self.STD_CATALOG_RE.search(n) is not None
                               for n in names])
        return has_sptype | (is_catalog & (texp <= self.STD_MAX_EXPTIME))

    def check_frame_type(self, ftype, fitstbl, exprng=None):
        """
        Check for frames of the provided type.

        Rules (design document, Section 4.3):

            - ``dark``: ``SFILTER == 'Drk'``
            - ``standard``: on-sky, and ``OBSTYPE`` starts with ``'s'`` or the
              target name looks like a standard (see
              :func:`is_standard_target`)
            - ``science``: every other on-sky frame (``OBSTYPE`` starts
              with ``'a'``); pairing is done via ``comb_id``/``bkg_id``
            - ``sky``: on-sky frames with ``ISSKY == 1``
            - ``trace``, ``arc``, ``tilt``: same as ``science`` (block-slit
              definition and OH lines)
            - all other types: never

        Generated by JXP and Claude.

        Args:
            ftype (:obj:`str`):
                Type of frame to check. Must be a valid frame type; see
                frame-type :ref:`frame_type_defs`.
            fitstbl (`astropy.table.Table`_):
                The table with the metadata for one or more frames to check.
            exprng (:obj:`list`, optional):
                Range in the allowed exposure time for a frame of type
                ``ftype``. See
                :func:`pypeit.core.framematch.check_frame_exptime`.

        Returns:
            `numpy.ndarray`_: Boolean array with the flags selecting the
            exposures in ``fitstbl`` that are ``ftype`` type frames.
        """
        good_exp = framematch.check_frame_exptime(fitstbl['exptime'], exprng)
        dispname = np.array([str(d).strip() for d in fitstbl['dispname']])
        idname = np.array([str(i).strip().lower() for i in fitstbl['idname']])
        is_dark = dispname == 'Drk'
        # Every non-dark frame taken as 'astro' or 'star' is on the sky
        on_sky = np.logical_not(is_dark) & np.isin(idname, ['a', 's'])
        is_std = on_sky & ((idname == 's')
                           | self.is_standard_target(fitstbl['target'],
                                                     fitstbl['exptime']))
        is_sci = on_sky & np.logical_not(is_std)

        if ftype == 'dark':
            return good_exp & is_dark
        if ftype == 'standard':
            return good_exp & is_std
        if ftype in ['science', 'trace', 'arc', 'tilt']:
            return good_exp & is_sci
        if ftype == 'sky':
            issky = np.array([0 if i is None else int(i)
                              for i in fitstbl['issky']])
            return good_exp & on_sky & (issky == 1)

        log.debug(f'Cannot determine if frames are of type {ftype}.')
        return np.zeros(len(fitstbl), dtype=bool)

    def vet_assigned_ftypes(self, type_bits, fitstbl):
        """
        Vet the automatically assigned frame types.

        In addition to the base-class checks, this warns (at
        ``pypeit_setup`` time) about frames taken before the H2RG
        detector upgrade, which :func:`get_rawimage` will refuse.

        Generated by JXP and Claude.

        Args:
            type_bits (`numpy.ndarray`_):
                Array with the frame types assigned to each frame.
            fitstbl (:class:`~pypeit.metadata.PypeItMetaData`):
                The class holding the metadata for all the frames.

        Returns:
            `numpy.ndarray`_: The updated frame types.
        """
        type_bits = super().vet_assigned_ftypes(type_bits, fitstbl)
        mjd = np.array([np.nan if m is None else float(m)
                        for m in fitstbl['mjd']])
        old = mjd < self.MJD_H2RG
        if np.any(old):
            log.warning(f'{np.sum(old)} frame(s) predate the 2016-01-01 '
                        'H2RG detector upgrade and cannot be reduced by '
                        'PypeIt:')
            for f in fitstbl['filename'][old]:
                log.warning(f'    {f}')
        return type_bits

    def read_noise(self, sampmode, numreads):
        """
        Read noise (e-) of the H2RG for a given sampling mode.

        CDS (``SAMPMODE=2`` or a single read) gives 22 e-; MCDS
        (``SAMPMODE=3``) is interpolated in ``log(NUMREADS)`` between the
        Keck measurements (12.2 e- for 4, 8.1 e- for 16, 7.8 e- for 32
        reads) and held at 7.8 e- beyond 32 reads; up-the-ramp and unknown
        modes use 8 e-.

        Generated by JXP and Claude.

        Args:
            sampmode (:obj:`int` or None):
                Value of the ``SAMPMODE`` header card.
            numreads (:obj:`int` or None):
                Value of the ``NUMREADS`` header card.

        Returns:
            :obj:`float`: Read noise in electrons.
        """
        try:
            nreads = float(numreads)
        except (TypeError, ValueError):
            nreads = None
        if sampmode == 2 or (sampmode == 3 and nreads is not None
                             and nreads <= 1):
            return float(self.MCDS_RN[0])
        if sampmode == 3 and nreads is not None:
            return float(np.interp(np.log(nreads), np.log(self.MCDS_NREADS),
                                   self.MCDS_RN))
        return self.UTR_RN

    def get_detector_par(self, det, hdu=None):
        """
        Return metadata for the selected detector.

        The read noise is set from ``SAMPMODE``/``NUMREADS`` and the plate
        scale from ``SSCALE`` when ``hdu`` is provided.

        Generated by JXP and Claude.

        Args:
            det (:obj:`int`):
                1-indexed detector number.
            hdu (`astropy.io.fits.HDUList`_, optional):
                The open fits file with the raw image of interest.  If not
                provided, defaults are used (MCDS-16 read noise, 0.05
                arcsec lenslets).

        Returns:
            :class:`~pypeit.images.detector_container.DetectorContainer`:
            Object with the detector metadata.
        """
        if hdu is None:
            ronoise = self.read_noise(3, 16)
            platescale = 0.05
        else:
            hdr = hdu[0].header
            ronoise = self.read_noise(hdr.get('SAMPMODE', None),
                                      hdr.get('NUMREADS', None))
            platescale = self.platescale_from_header(hdr)

        detector_dict = dict(
            det=1,
            binning='1,1',
            dataext=0,
            # Spectra run along the detector rows (numpy axis 1) and the
            # wavelength *decreases* with column number (Keck wavelength
            # coefficients), so flip to have it increase with pixel.
            specaxis=1,
            specflip=True,
            spatflip=False,
            platescale=platescale,
            darkcurr=90.0,  # e-/pixel/hour (0.025 e-/s)
            saturation=65535.,
            nonlinear=0.80,  # 80 % of full well, as in the Keck DRP
            mincounts=-1e10,
            numamplifiers=1,
            gain=np.atleast_1d(2.15),
            ronoise=np.atleast_1d(ronoise),
            datasec=np.atleast_1d('[1:2048,1:2048]'),
            oscansec=None,
        )
        return detector_container.DetectorContainer(**detector_dict)

    def check_era(self, mjd, filename=None):
        """
        Raise an error for data taken before the 2016 detector upgrade.

        Generated by JXP and Claude.

        Args:
            mjd (:obj:`float`):
                Modified Julian Date of the observation.
            filename (:obj:`str`, `Path`_, optional):
                File name used in the error message.

        Raises:
            PypeItError:
                Raised if ``mjd`` is before 2016-01-01 (MJD 57388) or is
                undefined.
        """
        fname = '' if filename is None else f' ({Path(filename).name})'
        if mjd is None or not np.isfinite(mjd):
            raise PypeItError(f'Cannot determine MJD-OBS{fname}; Keck/OSIRIS '
                              'frames must be dated to check the detector '
                              'era.')
        if mjd < self.MJD_H2RG:
            raise PypeItError(
                f'Keck/OSIRIS frame{fname} was taken on MJD {mjd:.1f}, '
                'before the 2016-01-01 H2RG detector upgrade (MJD 57388). '
                'Pre-2016 (Hawaii-2) OSIRIS data are not supported by '
                'PypeIt; use the Keck OSIRIS DRP instead.')

    def get_rawimage(self, raw_file, det):
        """
        Read a raw OSIRIS frame.

        The ``SCI`` extension is stored in ADU per second per coadd; it is
        converted to ADU (DN) by multiplying by ``ITIME x COADDS`` (in
        seconds).  The ``VAR`` and ``DQ`` extensions remain available in the
        returned ``hdu`` (see :func:`read_var_dq`).  Frames taken before
        2016-01-01 are rejected.

        Generated by JXP and Claude.

        Parameters
        ----------
        raw_file : :obj:`str`, `Path`_
            File to read
        det : :obj:`int`
            1-indexed detector to read

        Returns
        -------
        detector_par : DetectorContainer
            Detector metadata parameters
            (:class:`~pypeit.images.detector_container.DetectorContainer`).
        raw_img : `numpy.ndarray`_
            Raw image for this detector, in ADU.
        hdu : `astropy.io.fits.HDUList`_
            Opened fits file
        exptime : :obj:`float`
            Exposure time in seconds
        rawdatasec_img : `numpy.ndarray`_
            Data (Science) section of the detector (1 everywhere; a single
            amplifier is assumed).
        oscansec_img : `numpy.ndarray`_
            Overscan section of the detector (0 everywhere; no overscan).

        Raises
        ------
        PypeItError
            Raised for frames taken before the H2RG detector upgrade.
        """
        fil = utils.find_single_file(f'{raw_file}*', required=True)
        log.info(f'Reading Keck/OSIRIS file: {fil}')
        hdu = io.fits_open(fil)
        headarr = self.get_headarr(hdu)

        # Era check (H2RG only)
        mjd = self.get_meta_value(headarr, 'mjd')
        self.check_era(mjd, filename=fil)

        detpar = self.get_detector_par(1 if det is None else det, hdu=hdu)

        # Exposure time in seconds (ITIME in ms after 2016, x COADDS)
        exptime = self.get_meta_value(headarr, 'exptime')

        # ADU/s/coadd -> ADU
        raw_img = hdu[detpar['dataext']].data.astype(float) * exptime

        # Single read-out region, no overscan
        rawdatasec_img = np.ones(raw_img.shape, dtype=int)
        oscansec_img = np.zeros(raw_img.shape, dtype=int)

        return detpar, raw_img, hdu, exptime, rawdatasec_img, oscansec_img

    @staticmethod
    def read_var_dq(hdu):
        """
        Return the ``VAR`` and ``DQ`` extensions of a raw OSIRIS frame.

        The arrays are in the raw (detector) orientation and units: ``VAR``
        in ADU^2 per coadd and ``DQ`` a bitmap where 9 means good.

        Generated by JXP and Claude.

        Args:
            hdu (`astropy.io.fits.HDUList`_):
                Opened raw file.

        Returns:
            :obj:`tuple`: The ``VAR`` and ``DQ`` arrays (`numpy.ndarray`_);
            either is None if the extension is missing.
        """
        out = []
        for extname, extnum in [('VAR', 1), ('DQ', 2)]:
            names = [h.name for h in hdu]
            if extname in names:
                out.append(np.asarray(hdu[extname].data))
            elif len(hdu) > extnum:
                # Pre-2016 files have no EXTNAME on these extensions
                out.append(np.asarray(hdu[extnum].data))
            else:
                out.append(None)
        return tuple(out)

