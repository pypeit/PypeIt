    def load_static_masks(self):
        """
        Load the Keck static hot- and dead-pixel masks.

        The hot-pixel mask (``badpixelmask20170902_sigma50``) uses 9 = good,
        0 = bad; the dead-pixel mask (``bpm_dead_4pixbufgood``) uses 1 =
        good, 0 = bad.  Both are in the raw detector orientation.

        Generated by JXP and Claude.

        Returns:
            :obj:`tuple`: Two boolean `numpy.ndarray`_ objects (2048 x 2048),
            True for hot and dead pixels, respectively.
        """
        path = self.static_calib_path()
        hot = fits.getdata(path.get_file_path(
            'badpixelmask20170902_sigma50.fits.gz'))
        dead = fits.getdata(path.get_file_path(
            'bpm_dead_4pixbufgood.fits.gz'))
        return hot != 9, dead == 0

    def bpm(self, filename, det, shape=None, msbias=None):
        """
        Generate the default bad-pixel mask.

        The mask is ``DQ != 9`` (when a file is provided) OR the Keck static
        hot-pixel mask OR the Keck dead-pixel mask, re-oriented to the
        PypeIt (spectral, spatial) frame.

        Generated by JXP and Claude.

        Args:
            filename (:obj:`str` or None):
                An example file to use to get the image shape and the ``DQ``
                extension.
            det (:obj:`int`):
                1-indexed detector number.
            shape (tuple, optional):
                Processed image shape.  Required if filename is None; ignored
                otherwise.
            msbias (`numpy.ndarray`_, optional):
                Processed bias frame used to identify bad pixels.

        Returns:
            `numpy.ndarray`_: An integer array with a masked value set
            to 1 and an unmasked value set to 0.
        """
        bpm_img = super().bpm(filename, det, shape=shape, msbias=msbias)

        # Static masks, in the raw orientation
        hot, dead = self.load_static_masks()
        bad = hot | dead

        # Per-frame data-quality bitmap (9 = good)
        if filename is not None:
            with io.fits_open(filename) as hdu:
                _, dq = self.read_var_dq(hdu)
            if dq is not None and dq.shape == bad.shape:
                bad |= dq != 9

        # Re-orient to the PypeIt frame and apply
        detpar = self.get_detector_par(1 if det is None else det)
        bad = self.orient_image(detpar, bad)
        if bad.shape != bpm_img.shape:
            log.warning('Keck/OSIRIS static masks do not match the image '
                        f'shape {bpm_img.shape}; not applied.')
            return bpm_img
        bpm_img[bad] = 1
        return bpm_img

    def wave_coeff_epochs(self):
        """
        Load the table of Keck wavelength-coefficient epochs.

        Derived from ``calibrations.xml`` of the OSIRIS DRP; columns are
        ``begin``, ``end`` (YYMMDD), ``mjd_begin``, ``mjd_end`` and
        ``file``.

        Generated by JXP and Claude.

        Returns:
            `astropy.table.Table`_: The epoch table.
        """
        return Table.read(self.spec_data_path().get_file_path(
            'wave_coeff_epochs.ecsv'), format='ascii.ecsv')

    def wave_coeff_file(self, mjd):
        """
        Select the Keck wavelength-coefficient file for an observation.

        The latest epoch starting on or before ``mjd`` is used (the DRP
        uses the same table, with inclusive end dates).

        Generated by JXP and Claude.

        Args:
            mjd (:obj:`float`):
                Modified Julian Date of the observation.

        Returns:
            `Path`_: Full path to the coefficient file.

        Raises:
            PypeItError:
                Raised if ``mjd`` predates the first epoch.
        """
        epochs = self.wave_coeff_epochs()
        indx = np.where(epochs['mjd_begin'] <= mjd)[0]
        if len(indx) == 0:
            raise PypeItError(f'No Keck/OSIRIS wavelength solution for MJD '
                              f'{mjd}; the first epoch starts on MJD '
                              f'{np.min(epochs["mjd_begin"])}.')
        best = indx[np.argmax(epochs['mjd_begin'][indx])]
        return self.spec_data_path().get_file_path(epochs['file'][best])

    def load_wave_coeffs(self, mjd):
        """
        Load the Keck per-lenslet wavelength coefficients for an epoch.

        The coefficients give the detector pixel as a polynomial in
        ``lambda * order / 3 / frac_expan - 2200`` (nm), with
        ``coeffs[row, col, :]`` for the 66 x 51 lenslet grid.

        Generated by JXP and Claude.

        Args:
            mjd (:obj:`float`):
                Modified Julian Date of the observation.

        Returns:
            `numpy.ndarray`_: Array with shape (66, 51, 4).
        """
        return fits.getdata(self.wave_coeff_file(mjd)).astype(float)

    def load_al_cte(self):
        """
        Load the aluminium thermal-expansion table used by the DRP.

        Generated by JXP and Claude.

        Returns:
            `astropy.table.Table`_: Table with columns ``temp`` (K) and
            ``cte``.
        """
        return Table.read(self.spec_data_path().get_file_path('al_cte.ecsv'),
                          format='ascii.ecsv')

    def grating_expansion(self, tmatemp):
        """
        Fractional expansion of the grating relative to the reference
        wavelength solution, as in the DRP ``assembcube_000.pro``:
        ``(1 + cte(T)) / (1 + cte(50.73 K))``.

        Generated by JXP and Claude.

        Args:
            tmatemp (:obj:`float` or None):
                TMA temperature (K; header ``DTMP7``).  If None, no
                correction is applied and 1 is returned.

        Returns:
            :obj:`float`: The expansion factor (divide wavelengths by it).
        """
        if tmatemp is None:
            return 1.0
        cte = self.load_al_cte()
        cotemp = np.interp(tmatemp, cte['temp'], cte['cte'])
        coref = np.interp(self.TEMP_REF_WAVE, cte['temp'], cte['cte'])
        return float((1 + cotemp) / (1 + coref))

    def load_slice_to_lenslet(self):
        """
        Load the broadband (Kbb, 2016) slice-to-lenslet map.

        Generated by JXP and Claude.

        Returns:
            `numpy.ndarray`_: Integer array with shape (1216, 3) holding the
            rectification-matrix slice index and the lenslet row and column
            (column relative to the first broadband column).
        """
        return np.loadtxt(self.spec_data_path().get_file_path(
            'kbb_2016_slice_to_lenslet.txt'), dtype=int)

