    @classmethod
    def default_pypeit_par(cls):
        """
        Return the default parameters to use for this instrument.

        Generated by JXP and Claude.

        Returns:
            :class:`~pypeit.par.pypeitpar.PypeItPar`: Parameters required by
            all of PypeIt methods.
        """
        par = super().default_pypeit_par()

        # Darks are matched to the science frames by exposure time only
        par['calibrations']['darkframe']['exprng'] = [None, None]

        # Image processing: no bias, overscan, flats or cosmic-ray masking
        # (the DRP recommends against LACosmic on >= 2016 data; cosmic rays
        # are removed by frame combination).  No dark subtraction by
        # default: A-B (or A-sky) subtraction removes it (Q&A 23); users
        # may turn it on for unpaired frames.
        par.reset_all_processimages_par(use_biasimage=False,
                                        use_overscan=False,
                                        use_darkimage=False,
                                        use_pixelflat=False,
                                        use_illumflat=False,
                                        use_specillum=False,
                                        mask_cr=False)
        par['scienceframe']['process']['spat_flexure_correct'] = False

        # Wavelengths: Keck coefficients as the template, refined on OH sky
        # lines (implemented in later milestones).  Vacuum wavelengths.
        par['calibrations']['wavelengths']['method'] = 'full_template'
        par['calibrations']['wavelengths']['lamps'] = ['OH_NIRES']
        par['calibrations']['wavelengths']['reference'] = 'sky'
        par['calibrations']['wavelengths']['fwhm'] = 2.0

        # No flat fielding (no lamp flats are taken)
        par['calibrations']['flatfield']['method'] = 'skip'

        # Fiber mode: one object per lenslet, no peak finding
        par['reduce']['findobj']['skip_second_find'] = True
        par['reduce']['findobj']['skip_final_global'] = True
        par['reduce']['skysub']['joint_fit'] = False
        par['reduce']['cube']['slit_spec'] = False

        # No spectral flexure correction
        par['flexure']['spec_method'] = 'skip'

        # Telluric correction / fluxing
        par['sensfunc']['algorithm'] = 'IR'
        par['sensfunc']['IR']['telgridfile'] \
                = 'TellPCA_3000_26000_R10000.fits'

        return par

    def config_specific_par(self, inp, inp_par=None) -> parset.ParSet:
        """
        Modify the PypeIt parameters for a specific configuration.

        Sets the boxcar radius to half a lenslet (one rectified row).

        Generated by JXP and Claude.

        Args:
            inp (:obj:`str`, :obj:`list`, `Path`_,
                `astropy.io.fits.Header`_, `astropy.table.Table`_):
                Input filename, an `astropy.io.fits.Header`_ object, or a list
                of `astropy.io.fits.Header`_ objects.  Or a row from the
                metadata table.
            inp_par (:class:`~pypeit.par.parset.ParSet`, optional):
                Parameter set used for the full run of PypeIt.  If None,
                use :func:`default_pypeit_par`.

        Returns:
            :class:`~pypeit.par.parset.ParSet`: The PypeIt parameter set
            adjusted for configuration specific parameter values.
        """
        par = super().config_specific_par(inp, inp_par=inp_par)
        decker = self.get_meta_value(inp, 'decker')
        try:
            par['reduce']['extraction']['boxcar_radius'] \
                    = 0.5 * float(decker)
        except (TypeError, ValueError):
            log.warning(f'Could not parse the lenslet scale ({decker}); '
                        'keeping the default boxcar radius.')
        return par
