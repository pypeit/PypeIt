    # Lenslet bookkeeping (state of the frame being reduced)
    # ------------------------------------------------------------------
    def set_lenslet_state(self, filt, mjd, scale=None):
        """
        Record the filter, date and lenslet scale of the data being reduced.

        The lenslet layout (which spatial pixel of the rectified image holds
        which lenslet) depends on the filter (broadband or narrowband) and on
        the epoch of the Keck wavelength coefficients.  The Fiber-pypeline
        hooks (:func:`get_fiber_blocks`, :func:`get_fiber_metadata`, ...) do
        not receive a header, so the state is set by :func:`rectify` and
        :func:`get_fixed_wavecalib` from the frame being processed (the same
        mechanism as the ``dispname`` attribute used for echelle
        spectrographs).  Scripts working on reduced files call this method
        directly.

        Generated by JXP and Claude.

        Args:
            filt (:obj:`str`):
                Filter name (header ``SFILTER``).
            mjd (:obj:`float`):
                MJD of the observation.
            scale (:obj:`float`, optional):
                Lenslet scale in arcsec (header ``SSCALE``).
        """
        self.dispname = str(filt).strip()
        self.lenslet_mjd = float(mjd)
        if scale is not None:
            self.lenslet_scale = float(scale)

    def _set_state_from_header(self, hdr):
        """
        Set the lenslet state from a raw header.

        Generated by JXP and Claude.

        Args:
            hdr (`astropy.io.fits.Header`_):
                Primary header of a raw frame.
        """
        # Truncated headers: name the missing cards instead of a KeyError
        missing = [k for k in ['SFILTER', 'MJD-OBS'] if k not in hdr]
        if len(missing) > 0:
            fname = hdr.get('DATAFILE', hdr.get('FILENAME', 'the frame'))
            raise PypeItError(f'Header of {fname} lacks {", ".join(missing)}'
                              '; the Keck/OSIRIS filter and date are needed '
                              'to select the lenslet layout, wavelength '
                              'coefficients and rectification matrix.')
        self.set_lenslet_state(hdr['SFILTER'], hdr['MJD-OBS'],
                               scale=self.platescale_from_header(hdr))

    def _require_state(self):
        """
        Check that the lenslet state has been set.

        Generated by JXP and Claude.

        Raises:
            PypeItError:
                Raised if :func:`set_lenslet_state` has not been called.
        """
        if self.dispname is None or getattr(self, 'lenslet_mjd', None) \
                is None:
            raise PypeItError('Keck/OSIRIS lenslet layout requested before '
                              'the filter and date are known; call '
                              'set_lenslet_state() first.')

    def lenslet_layout(self):
        """
        Lenslet layout of the current filter and epoch.

        See :func:`pypeit.core.lenslet_rectify.lenslet_layout`.  The result
        is cached on the instance.

        Generated by JXP and Claude.

        Returns:
            `astropy.table.Table`_: One row per lenslet.
        """
        self._require_state()
        cfile = Path(self.wave_coeff_file(self.lenslet_mjd)).name
        key = (self.dispname, cfile)
        cache = getattr(self, '_layout_cache', {})
        if key not in cache:
            coeffs = self.load_wave_coeffs(self.lenslet_mjd)
            cache = {key: lenslet_rectify.lenslet_layout(
                self.dispname, coeffs, nslice=self.NSLICE_BB)}
            self._layout_cache = cache
        return cache[key]

    def lenslet_wavelengths(self, frac):
        """
        Vacuum wavelengths of every lenslet of the current layout.

        Inverts the Keck relation (see
        :func:`pypeit.core.lenslet_rectify.keck_wavelengths`) for every
        lenslet of :func:`lenslet_layout`; cached on the instance.

        Generated by JXP and Claude.

        Args:
            frac (:obj:`float`):
                Grating expansion factor (see :func:`grating_expansion`).

        Returns:
            `numpy.ndarray`_: Wavelengths in nm with shape (nlenslet, 2048),
            indexed by the *raw* detector column (wavelength decreases
            with column).
        """
        lay = self.lenslet_layout()
        cfile = Path(self.wave_coeff_file(self.lenslet_mjd)).name
        key = (self.dispname, cfile, round(float(frac), 10))
        cache = getattr(self, '_lambda_cache', {})
        if key not in cache:
            coeffs = self.load_wave_coeffs(self.lenslet_mjd)
            cl = coeffs[lay['crow'], lay['ccol']]
            cache = {key: lenslet_rectify.keck_wavelengths(
                cl, lenslet_rectify.keck_order(self.dispname), frac=frac,
                ncol=lay.meta['ncol'])}
            self._lambda_cache = cache
        return cache[key]

    def frame_expansion(self, hdr, apply=None):
        """
        Grating expansion factor for a raw header.

        The DRP grating-temperature term (``DTMP7``; see
        :func:`grating_expansion`) is applied only when ``apply`` is True;
        by default the choice follows the ``osiris_grating_temp``
        calibration parameter, which is False because the term moves the OH
        lines away from their vacuum wavelengths on both the 2016 Hn3 and
        the 2024 Kbb test data (M3 Q&A 4, M4 task 9).  A missing ``DTMP7``
        gives no correction, with a warning (M2 Q&A 4).

        Generated by JXP and Claude.

        Args:
            hdr (`astropy.io.fits.Header`_):
                Raw primary header.
            apply (:obj:`bool`, optional):
                Apply the term; if None, use the ``osiris_grating_temp``
                parameter of the run (or of the defaults).

        Returns:
            :obj:`float`: The expansion factor (1 when not applied).
        """
        if apply is None:
            apply = bool(self._calib_par()['osiris_grating_temp'])
        if not apply:
            return 1.0
        tmatemp = hdr.get('DTMP7', None)
        if tmatemp is None:
            log.warning('DTMP7 (grating temperature) is missing from the '
                        'header; no grating-expansion correction is applied '
                        'to the Keck wavelengths.')
            return 1.0
        return self.grating_expansion(float(tmatemp))

