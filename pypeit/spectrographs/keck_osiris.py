    # Rectification (RawImage.rectify step)
    # ------------------------------------------------------------------
    def _calib_par(self):
        """
        Calibration parameters of the current run.

        Generated by JXP and Claude.

        Returns:
            :class:`~pypeit.par.pypeitpar.CalibrationsPar`: The run
            parameters if set (see
            :func:`~pypeit.spectrographs.spectrograph.Spectrograph.set_runtime_par`),
            otherwise the defaults of this spectrograph.
        """
        if self.runtime_par is not None:
            return self.runtime_par['calibrations']
        if getattr(self, '_default_calib_par', None) is None:
            log.info('Run parameters not set; using the Keck/OSIRIS '
                     'defaults.')
            self._default_calib_par = \
                self.default_pypeit_par()['calibrations']
        return self._default_calib_par

    @staticmethod
    def unorient_image(detector_par, image):
        """
        Undo :func:`~pypeit.spectrographs.spectrograph.Spectrograph.orient_image`.

        Generated by JXP and Claude.

        Args:
            detector_par (:class:`~pypeit.images.detector_container.DetectorContainer`):
                Detector metadata.
            image (`numpy.ndarray`_):
                Image in the PypeIt orientation.

        Returns:
            `numpy.ndarray`_: Image in the raw orientation.
        """
        img = image
        if detector_par['spatflip']:
            img = np.flip(img, axis=1)
        if detector_par['specflip']:
            img = np.flip(img, axis=0)
        if detector_par['specaxis'] == 1:
            img = img.T
        return img

    def rect_matrix(self, hdr, cpar, filename=None):
        """
        Select, read and cache the rectification matrix of a frame.

        The matrix directory is ``osiris_rectmat_dir`` (environment
        variables are expanded); if it is not set, the directory of the raw
        file and its ``calib`` sub-directory are searched.

        Generated by JXP and Claude.

        Args:
            hdr (`astropy.io.fits.Header`_):
                Raw primary header (``SFILTER``, ``SSCALE``, ``MJD-OBS``).
            cpar (:class:`~pypeit.par.pypeitpar.CalibrationsPar`):
                Calibration parameters.
            filename (:obj:`str`, `Path`_, optional):
                Raw file (for the fallback search).

        Returns:
            :class:`~pypeit.core.lenslet_rectify.RectMatrix`: The matrix.
        """
        mdir = cpar['osiris_rectmat_dir']
        if mdir is not None:
            dirs = [Path(os.path.expandvars(str(mdir))).expanduser()]
        elif filename is not None:
            raw_dir = Path(filename).absolute().parent
            dirs = [raw_dir / 'calib', raw_dir]
            log.warning('osiris_rectmat_dir is not set; searching '
                        f'{dirs[0]} and {dirs[1]} for the rectification '
                        'matrix.')
        else:
            raise PypeItError('Set [calibrations] osiris_rectmat_dir to the '
                              'directory of the Keck rectification '
                              'matrices.')
        mfile, err = None, None
        for d in dirs:
            if not d.is_dir():
                continue
            try:
                mfile = lenslet_rectify.select_matrix(
                    d, str(hdr['SFILTER']).strip(), hdr['SSCALE'],
                    float(hdr['MJD-OBS']))
                break
            except PypeItError as e:
                err = e
        if mfile is None:
            searched = ', '.join([str(d) for d in dirs])
            raise err if err is not None else PypeItError(
                f'Rectification-matrix directory not found ({searched}); set '
                '[calibrations] osiris_rectmat_dir to the directory holding '
                'the Keck matrices (available from '
                f'{lenslet_rectify.RECTMAT_URL}).')
        cached = getattr(self, '_rect_matrix', None)
        if cached is None or cached.filename != mfile:
            self._rect_matrix = lenslet_rectify.RectMatrix.from_file(mfile)
        return self._rect_matrix

    def rectify(self, image, ivar, bpm, headarr, par, base_var=None,
                rn2img=None, filename=None):
        """
        Extract the lenslet spectra of a processed raw frame.

        Called by :func:`pypeit.images.rawimage.RawImage.rectify` after the
        dark subtraction (design document, section 5.3; M2 Q&A 1-4):

            1. un-orient the image (the matrix is in the raw orientation);
            2. subtract the per-column median of the unilluminated rows
               2032-2044 (DRP "Adjust Channel Levels");
            3. flag saturated pixels and cosmic rays on the raw frame
               (``osiris_rect_crmask``) into the BPM;
            4. solve with ``osiris_rect_method`` (``drp`` or the ``lstsq``
               solver with flux-independent weights);
            5. compute the variance with the least-squares machinery for
               either method (sandwich formula with the true pixel variance;
               separately for the read noise);
            6. map the slices onto the lenslet image (one spatial pixel per
               lenslet; see :func:`lenslet_layout`) and flip the spectral
               axis (``specflip``).

        Generated by JXP and Claude.

        Args:
            image (`numpy.ndarray`_):
                Processed image (PypeIt orientation, e-).
            ivar (`numpy.ndarray`_):
                Its inverse variance (full noise model).
            bpm (`numpy.ndarray`_):
                Boolean bad-pixel mask.
            headarr (:obj:`list`):
                Raw headers.
            par (:class:`~pypeit.par.pypeitpar.ProcessImagesPar`):
                Processing parameters (L.A.Cosmic settings, gain).
            base_var (`numpy.ndarray`_, optional):
                Flux-independent variance; defaults to the full variance.
            rn2img (`numpy.ndarray`_, optional):
                Read-noise variance; defaults to ``base_var``.
            filename (:obj:`str`, `Path`_, optional):
                Raw file (used to locate the matrix if
                ``osiris_rectmat_dir`` is not set).

        Returns:
            :obj:`dict`: ``image`` (rectified lenslet image, nspec x
            nlenslet-pixels), ``rn2img`` and ``proc_var`` (read-noise and
            remaining variance), and ``bpm`` (boolean).
        """
        t0 = time.perf_counter()
        hdr = headarr[0]
        self._set_state_from_header(hdr)
        cpar = self._calib_par()
        detpar = self.get_detector_par(1)

        # 1. Raw orientation
        img0 = np.asarray(self.unorient_image(detpar, image), dtype=float)
        var = self.unorient_image(detpar, utils.inverse(ivar))
        raw_bpm = np.array(self.unorient_image(detpar, bpm), dtype=bool) \
            | np.logical_not(self.unorient_image(detpar, ivar) > 0)
        bvar = var if base_var is None \
            else self.unorient_image(detpar, base_var)
        rn2 = bvar if rn2img is None else self.unorient_image(detpar, rn2img)

        # 2. Column offsets from the reference rows
        img = lenslet_rectify.subtract_reference_rows(img0)

        # 3. Saturation (raw counts) and cosmic rays
        gain = float(detpar['gain'][0]) if par['apply_gain'] else 1.
        sat = img0 >= detpar['saturation'] * detpar['nonlinear'] * gain
        raw_bpm |= sat
        crmeth = cpar['osiris_rect_crmask']
        crmask = np.zeros_like(raw_bpm)
        if crmeth == 'lacosmic':
            crmask = procimg.lacosmic(img, bpm=raw_bpm, varframe=var,
                                      maxiter=par['lamaxiter'],
                                      grow=par['grow'],
                                      remove_compact_obj=par['rmcompact'],
                                      sigclip=par['sigclip'],
                                      sigfrac=par['sigfrac'],
                                      objlim=par['objlim'])
        elif crmeth == 'drp2016':
            crmask = lenslet_rectify.cosmic_mask_drp2016(img)[1]
        raw_bpm |= crmask
        log.info(f'Raw-frame masks: {int(np.sum(sat))} saturated and '
                 f'{int(np.sum(crmask))} cosmic-ray pixels ({crmeth}).')

        # 4. Solve.  The weights are flux independent: read noise, dark,
        # processing variance and a smooth background (M2 Q&A 1).
        matrix = self.rect_matrix(hdr, cpar, filename=filename)
        weights = utils.inverse(lenslet_rectify.background_variance(
            img, bvar, raw_bpm))
        method = cpar['osiris_rect_method']
        log.info(f'Rectifying with the {method} solver and '
                 f'{matrix.filename.name}')
        if method == 'lstsq':
            rect, rivar, rbpm = lenslet_rectify.rectify_lstsq(
                img, weights, raw_bpm, matrix, var=var)
            var_tot = utils.inverse(rivar)
            # 5. Read-noise part of the variance
            (var_rn,), vbpm = lenslet_rectify.lstsq_variance(
                weights, raw_bpm, matrix, [rn2])
        else:
            rect, _, rbpm = lenslet_rectify.rectify_drp(
                img, raw_bpm, matrix, niter=cpar['osiris_rect_niter'],
                relax=cpar['osiris_rect_relax'])
            # 5. Variance from the least-squares machinery (M2 Q&A 3)
            (var_tot, var_rn), vbpm = lenslet_rectify.lstsq_variance(
                weights, raw_bpm, matrix, [var, rn2])
        rbpm = rbpm | vbpm | np.logical_not(var_tot > 0)

        # 6. Lenslet image, then flip the spectral axis
        lay = self.lenslet_layout()
        limg, (lvt, lvr), lbpm = lenslet_rectify.lenslet_image(
            rect, lay, rect_extra=[var_tot, var_rn], bpm=rbpm)
        log.info(f'Rectification of {hdr.get("DATAFILE", "frame")} took '
                 f'{time.perf_counter() - t0:.1f} s; {len(lay)} lenslets.')
        return dict(image=np.ascontiguousarray(limg[::-1], dtype=float),
                    rn2img=np.ascontiguousarray(lvr[::-1], dtype=float),
                    proc_var=np.ascontiguousarray(
                        np.clip(lvt - lvr, 0., None)[::-1], dtype=float),
                    bpm=np.ascontiguousarray(lbpm[::-1]))

