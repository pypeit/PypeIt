# Matrix file names, e.g. s160318_c005___infl_Hn3_100.fits
MATRIX_RE = re.compile(r'^s(\d{6})_c(\d+)___infl_([A-Za-z0-9]+)_(\d{3})'
                       r'\.fits(\.gz)?$')


def parse_matrix_filename(filename):
    """
    Parse the name of a Keck rectification-matrix file.

    Generated by JXP and Claude.

    Args:
        filename (:obj:`str`, `Path`_):
            File name (any directory part is ignored), e.g.
            ``s160318_c005___infl_Hn3_100.fits``.

    Returns:
        :obj:`dict` or None: None if the name does not follow the Keck
        convention; otherwise a dictionary with keys ``date`` (ISO date
        string), ``mjd`` (MJD at 00:00 UT of that date), ``cnum``
        (calibration sequence number), ``filter`` (e.g. ``'Hn3'``) and
        ``scale`` (lenslet scale in arcsec, e.g. 0.1).
    """
    m = MATRIX_RE.match(Path(filename).name)
    if m is None:
        return None
    yymmdd, cnum, filt, scale = m.group(1), m.group(2), m.group(3), \
        m.group(4)
    date = f'20{yymmdd[:2]}-{yymmdd[2:4]}-{yymmdd[4:]}'
    return dict(date=date, mjd=float(Time(date, scale='utc').mjd),
                cnum=int(cnum), filter=filt, scale=int(scale) / 1000.)


RECTMAT_URL = 'http://tkserver.keck.hawaii.edu/osiris/'
"""Keck listing of the rectification matrices by validity epoch."""


def load_matrix_epochs():
    """
    Load the table of rectification-matrix validity epochs.

    Keck builds one rectification matrix per (filter, scale) and *validity
    epoch*; the date in the file name is only the date of the calibration
    scan and may fall after observations it serves.  The epochs are copied
    from :data:`RECTMAT_URL` into
    ``pypeit/data/spectrographs/keck_osiris/rectmat_epochs.ecsv``.

    Generated by JXP and Claude.

    Returns:
        `astropy.table.Table`_: One row per epoch with columns ``begin``,
        ``end`` (UT dates YYMMDD; ``end = 'open'`` for the current epoch),
        ``mjd_begin``, ``mjd_end`` (00:00 UT of the first day and of the day
        after the last day; ``inf`` when open) and ``subdir`` (directory
        name on the Keck server).
    """
    return Table.read(dataPaths.spectrographs.get_file_path(
        'keck_osiris/rectmat_epochs.ecsv'), format='ascii.ecsv')


def matrix_epoch(mjd, epochs=None):
    """
    Find the rectification-matrix validity epoch of an observation.

    Generated by JXP and Claude.

    Args:
        mjd (:obj:`float`):
            MJD of the observation.
        epochs (`astropy.table.Table`_, optional):
            Epoch table (see :func:`load_matrix_epochs`); loaded if None.

    Returns:
        :obj:`tuple`: The table row of the epoch and a boolean that is True
        when ``mjd`` lies inside it (False when it falls in a gap between
        epochs, or outside the table, and the nearest epoch is returned).
    """
    tbl = load_matrix_epochs() if epochs is None else epochs
    beg = np.asarray(tbl['mjd_begin'], dtype=float)
    end = np.asarray(tbl['mjd_end'], dtype=float)
    inside = np.where((mjd >= beg) & (mjd < end))[0]
    if len(inside) > 0:
        return tbl[inside[0]], True
    # In a gap (or outside the table): the epoch with the nearest boundary
    dist = np.minimum(np.abs(mjd - beg), np.abs(mjd - end))
    return tbl[int(np.argmin(dist))], False


def select_matrix(directory, filt, scale, mjd, epochs=None):
    """
    Select the rectification matrix for an observation.

    Keck releases one matrix per (filter, scale) and validity epoch (see
    :data:`RECTMAT_URL` and :func:`load_matrix_epochs`); its file date is
    the date of the calibration scan, which may be *after* the
    observations it serves (e.g. ``s240524_c006___infl_Kbb_050`` for
    2024-02-03).  The rule is therefore:

        1. find the epoch containing the observation (the nearest epoch,
           with a warning, if the date falls in a gap between epochs);
        2. among the matrices of the requested filter and scale, return the
           one whose file date lies inside that epoch (latest date, then
           highest sequence number, if several do);
        3. if none does, fall back to the latest matrix dated on or before
           the observation, with a warning.

    Plain (``.fits``) and gzipped (``.fits.gz``) files are accepted.

    Generated by JXP and Claude.

    Args:
        directory (:obj:`str`, `Path`_):
            Directory holding the Keck matrices.
        filt (:obj:`str`):
            Filter name (header ``SFILTER``), e.g. ``'Hn3'``.
        scale (:obj:`str`, :obj:`float`):
            Lenslet scale in arcsec (header ``SSCALE``), e.g. ``'0.100'``.
        mjd (:obj:`float`):
            MJD of the observation.
        epochs (`astropy.table.Table`_, optional):
            Epoch table (see :func:`load_matrix_epochs`); loaded if None.

    Returns:
        `Path`_: The selected matrix file.

    Raises:
        PypeItError:
            Raised if the directory does not exist or holds no suitable
            matrix; the message lists the matrices that were found and the
            epoch that applies.
    """
    _dir = Path(directory).expanduser()
    if not _dir.is_dir():
        raise PypeItError(f'Rectification-matrix directory {_dir} does not '
                          'exist; set [calibrations] osiris_rectmat_dir to '
                          'the directory holding the Keck matrices '
                          f'(available from {RECTMAT_URL}).')
    _scale = float(scale)
    found, other = [], []
    for f in sorted(_dir.iterdir()):
        info = parse_matrix_filename(f)
        if info is not None:
            found.append((f, info))
        elif not f.name.startswith('.'):
            other.append(f.name)
    # Matrices of the requested mode
    mode = [(f, i) for f, i in found
            if i['filter'] == filt and abs(i['scale'] - _scale) < 1e-4]

    # 1. Validity epoch of the observation
    epoch, in_epoch = matrix_epoch(mjd, epochs=epochs)
    ep_str = f'{epoch["begin"]}-{epoch["end"]}'
    date = Time(mjd, format='mjd').iso[:10]
    if not in_epoch:
        log.warning(f'MJD {mjd:.2f} ({date}) falls outside the Keck '
                    'rectification-matrix validity epochs; using the nearest '
                    f'epoch, {ep_str}.')

    # 2. A matrix whose file date lies inside the epoch
    inside = [(f, i) for f, i in mode
              if epoch['mjd_begin'] <= i['mjd'] < epoch['mjd_end']]
    if len(inside) > 0:
        best = max(inside, key=lambda fi: (fi[1]['mjd'], fi[1]['cnum']))
        return best[0]

    # 3. Fallback: the latest matrix on or before the observation
    before = [(f, i) for f, i in mode if i['mjd'] <= mjd]
    if len(before) > 0:
        best = max(before, key=lambda fi: (fi[1]['mjd'], fi[1]['cnum']))
        log.warning(f'No {filt}/{_scale:.3f}" rectification matrix in {_dir} '
                    f'belongs to the validity epoch {ep_str} of {date}; '
                    f'falling back to {best[0].name}, the latest matrix dated '
                    'on or before the observation.  The matrix for this '
                    f'epoch is available from {RECTMAT_URL}.')
        return best[0]

    listing = '\n'.join(
        [f'    {f.name}: {i["filter"]} {i["scale"]:.3f}" {i["date"]}'
         for f, i in found]) if len(found) > 0 else '    (none)'
    # Other files, e.g. matrices renamed or compressed differently (only
    # sYYMMDD_cNNN___infl_<filter>_<scale>.fits[.gz] names are recognised)
    nshow = 20
    others = '\n'.join([f'    {n}' for n in other[:nshow]]) \
        if len(other) > 0 else '    (none)'
    if len(other) > nshow:
        others += f'\n    ... and {len(other) - nshow} more'
    raise PypeItError(
        f'No Keck/OSIRIS rectification matrix for filter {filt}, scale '
        f'{_scale:.3f} arcsec and MJD {mjd:.2f} ({date}; validity epoch '
        f'{ep_str}) in {_dir}.  Matrices found:\n{listing}\nOther files '
        f'(names must follow sYYMMDD_cNNN___infl_<filter>_<scale>.fits'
        f'[.gz]):\n{others}\nDownload the matrix of epoch {ep_str} from '
        f'{RECTMAT_URL} (data/{epoch["subdir"]}/).')


class RectMatrix:
    """
    A Keck/OSIRIS rectification (influence) matrix.

    Generated by JXP and Claude.

    Args:
        hilo (`numpy.ndarray`_):
            Integer array (nslice, 2) with the bottom and top detector rows
            of each slice window.
        effective (`numpy.ndarray`_):
            Integer array (nslice,), 1 for illuminated slices.
        influence (`numpy.ndarray`_):
            Float array (nslice, nwin, ncol) with the slice profiles; row
            ``l`` of the window is detector row ``hilo[s,0] + l``.
        header (`astropy.io.fits.Header`_, optional):
            Primary header of the matrix file (``BASESIZE``, ``WTLIMIT``,
            ``SLICE``, ``SHIFT``).
        filename (:obj:`str`, `Path`_, optional):
            File the matrix was read from; its name is parsed with
            :func:`parse_matrix_filename`.

    Attributes:
        hilo, effective, influence, header, filename:
            As above.
        info (:obj:`dict`):
            Parsed file name (empty if not available).
    """

    def __init__(self, hilo, effective, influence, header=None,
                 filename=None):
        self.hilo = np.asarray(hilo, dtype=int)
        self.effective = np.asarray(effective, dtype=int)
        self.influence = np.asarray(influence, dtype=np.float32)
        if self.influence.ndim != 3 \
                or self.influence.shape[0] != self.hilo.shape[0]:
            raise PypeItError('Influence cube must have shape (nslice, nwin, '
                              'ncol) matching hilo.')
        self.header = fits.Header() if header is None else header
        self.filename = None if filename is None else Path(filename)
        info = None if filename is None else parse_matrix_filename(filename)
        self.info = {} if info is None else info

    @classmethod
    def from_file(cls, filename):
        """
        Read a Keck rectification-matrix file.

        Generated by JXP and Claude.

        Args:
            filename (:obj:`str`, `Path`_):
                Matrix file.

        Returns:
            :class:`RectMatrix`: The matrix.
        """
        _file = Path(filename).expanduser()
        if not _file.is_file():
            raise PypeItError(f'Rectification matrix {_file} not found.')
        log.info(f'Reading OSIRIS rectification matrix {_file.name}')
        with fits.open(_file) as hdu:
            return cls(hdu[0].data, hdu[1].data, hdu[2].data,
                       header=hdu[0].header.copy(), filename=_file)

    @property
    def nslice(self):
        """Number of slices (1216 for OSIRIS). Generated by JXP and Claude."""
        return self.influence.shape[0]

    @property
    def nwin(self):
        """Rows in each slice window (16). Generated by JXP and Claude."""
        return self.influence.shape[1]

    @property
    def ncol(self):
        """Detector columns (2048). Generated by JXP and Claude."""
        return self.influence.shape[2]

    @property
    def bottom(self):
        """Bottom row of each slice window. Generated by JXP and Claude."""
        return self.hilo[:, 0]

    def param(self, key, default=None):
        """
        Return a header parameter (``BASESIZE``, ``WTLIMIT``, ``SLICE``,
        ``SHIFT``) of the matrix.

        Generated by JXP and Claude.

        Args:
            key (:obj:`str`):
                Header keyword.
            default (object, optional):
                Value returned if the keyword is absent.

        Returns:
            object: The header value.
        """
        return self.header.get(key, default)

    def row_index(self, nrow):
        """
        Detector row of every (slice, window row) element.

        Generated by JXP and Claude.

        Args:
            nrow (:obj:`int`):
                Number of detector rows; rows outside ``[0, nrow)`` are
                mapped to the padding row ``nrow`` (always empty).

        Returns:
            `numpy.ndarray`_: Integer array (nslice, nwin).
        """
        rows = self.bottom[:, None] + np.arange(self.nwin)[None, :]
        return np.where((rows >= 0) & (rows < nrow), rows, nrow)

    def footprint(self):
        """
        Window rows that hold nonzero influence for each slice.

        Generated by JXP and Claude.

        Returns:
            :obj:`tuple`: Boolean ``active`` (nslice,) flagging slices with
            any nonzero influence, and integer ``first``/``last`` (nslice,)
            with the first and last nonzero window row.
        """
        nz = np.any(self.influence != 0, axis=2)
        active = nz.any(axis=1)
        first = np.argmax(nz, axis=1)
        last = self.nwin - 1 - np.argmax(nz[:, ::-1], axis=1)
        return active, first, last


def _check_inputs(image, bpm, matrix):
    """
    Validate the image and mask against the matrix and pad them.

    One empty row is appended so that window rows falling off the
    detector can be pointed at it (see :func:`RectMatrix.row_index`).

    Generated by JXP and Claude.

    Args:
        image (`numpy.ndarray`_):
            Raw-orientation image (nrow, ncol).
        bpm (`numpy.ndarray`_, None):
            Bad-pixel mask (True = bad), same shape; None for no mask.
        matrix (:class:`RectMatrix`):
            The rectification matrix.

    Returns:
        :obj:`tuple`: The padded float image (nrow+1, ncol), the padded
        good-pixel mask (nrow+1, ncol) and the (nslice, nwin) row index.
    """
    if image.ndim != 2 or image.shape[1] != matrix.ncol:
        raise PypeItError(f'Image shape {image.shape} does not match the '
                          f'rectification matrix ({matrix.ncol} columns).  '
                          'Rectification works on the raw (unoriented) '
                          'frame.')
    nrow = image.shape[0]
    gpm = np.ones(image.shape, dtype=bool) if bpm is None \
        else np.logical_not(np.asarray(bpm, dtype=bool))
    if gpm.shape != image.shape:
        raise PypeItError('Bad-pixel mask and image shapes differ.')
    img = np.zeros((nrow + 1, matrix.ncol), dtype=np.float32)
    img[:nrow] = np.where(gpm, image, 0.)
    _gpm = np.zeros((nrow + 1, matrix.ncol), dtype=bool)
    _gpm[:nrow] = gpm
    return img, _gpm, matrix.row_index(nrow)


def blame_kernels(matrix):
    """
    Normalised "blame" kernels of the DRP solver.

    ``blame = B^3 / sum_l B^3`` (sharpened kernel used in the first 15
    iterations) and ``fblame = B / sum_l B`` (final kernel); both are
    zero where the normalisation vanishes.

    Generated by JXP and Claude.

    Args:
        matrix (:class:`RectMatrix`):
            The rectification matrix.

    Returns:
        :obj:`tuple`: ``blame`` and ``fblame`` (nslice, nwin, ncol)
        float32 arrays, and boolean (nslice, ncol) arrays flagging where
        ``sum B^3 > 0`` and ``sum B > 0``.
    """
    B = matrix.influence
    b3 = B * B * B
    w = b3.sum(axis=1)
    fw = B.sum(axis=1)
    wpos = w > 0
    fwpos = fw > 0
    blame = b3 / np.where(wpos, w, 1.)[:, None, :]
    fblame = B / np.where(fwpos, fw, 1.)[:, None, :]
    return blame.astype(np.float32), fblame.astype(np.float32), wpos, fwpos


def _good_fraction(fblame, gpm, rows):
    """
    Fraction of each slice kernel falling on good pixels (DRP mask rule).

    Generated by JXP and Claude.

    Args:
        fblame (`numpy.ndarray`_):
            Final blame kernel (nslice, nwin, ncol).
        gpm (`numpy.ndarray`_):
            Padded good-pixel mask (nrow+1, ncol).
        rows (`numpy.ndarray`_):
            Row index (nslice, nwin).

    Returns:
        `numpy.ndarray`_: Float array (nslice, ncol).
    """
    return np.sum(fblame * gpm[rows], axis=1)


def _scatter_operator(rows, nrow_pad):
    """
    Sparse operator adding window rows into detector rows.

    Generated by JXP and Claude.

    Args:
        rows (`numpy.ndarray`_):
            Row index (nslice, nwin).
        nrow_pad (:obj:`int`):
            Number of (padded) detector rows.

    Returns:
        `scipy.sparse.csr_matrix`_: Matrix (nrow_pad, nslice*nwin) such
        that ``P @ Y.reshape(nslice*nwin, ncol)`` sums the model of every
        slice into the detector rows.
    """
    n = rows.size
    return sparse.csr_matrix((np.ones(n, dtype=np.float32),
                              (rows.ravel(), np.arange(n))),
                             shape=(nrow_pad, n))


def rectify_drp(image, bpm, matrix, niter=40, relax=1.0, noise=None,
                norm=DRP_NORM, stride=NLENS_ROW):
    """
    Extract the lenslet spectra with the Keck OSIRIS DRP algorithm.

    Faithful, vectorised port of ``spatrectif_000.c`` (OsirisDRP).  All
    detector columns are solved simultaneously.  Starting from ``c = 0``,
    each iteration computes the residual ``r = F - B c`` on good pixels
    and then:

        - iterations 0-14: ``t_s = relax * sum_l r * blame``, with
          ``blame = B^3 / sum B^3``; the update is
          ``c_s += t_s + a * [(t_s - t_{s-64}) + (t_s - t_{s+64})]``
          with ``a = +0.4`` for iterations 0-9 and ``-0.2`` for 10-14
          (each neighbour term only if that neighbour has a nonzero
          kernel, and only for slices with a nonzero kernel);
        - iterations >= 15: ``c_s += relax * sum_l r * fblame`` with
          ``fblame = B / sum B``;
        - after iterations 12-17: ``c`` is smoothed along the dispersion
          with the kernel [0.1, 0.2, 0.4, 0.2, 0.1] (columns 2 to
          ncol-3 only).

    The solution is divided by ``norm`` (1.28 in the DRP).  The noise is
    propagated as in the DRP, ``sigma_s = sum_l fblame * sigma`` (good
    pixels only, no division by ``norm``), and a slice/column is good if
    more than half (4.5/9) of its ``fblame`` weight lies on good pixels.

    .. note::
        The C code tests the quality of detector row ``l`` (0-15) rather
        than row ``bottom + l`` when building the output mask and noise
        (an indexing slip); here the intended rows are used.

    Generated by JXP and Claude.

    Args:
        image (`numpy.ndarray`_):
            Raw-orientation image (2048 rows x 2048 columns; dispersion
            along axis 1), e.g. an A-B difference.  Any units.
        bpm (`numpy.ndarray`_, None):
            Bad-pixel mask (True = bad) in the same orientation.  Bad
            pixels are excluded from the residual.  None for no mask.
        matrix (:class:`RectMatrix`):
            The rectification matrix.
        niter (:obj:`int`, optional):
            Number of iterations (DRP default 40 for science frames).
        relax (:obj:`float`, optional):
            Relaxation factor (DRP ``relaxation``, default 1).
        noise (`numpy.ndarray`_, optional):
            Per-pixel noise (sigma, same units as ``image``).  If None the
            returned ``ivar`` is None.
        norm (:obj:`float`, optional):
            Normalisation dividing the solution (DRP: 1.28).
        stride (:obj:`int`, optional):
            Slice offset of the spatial neighbours used by the coupling
            term (64 lenslet rows per lenslet column).

    Returns:
        :obj:`tuple`: ``rect`` (ncol, nslice) float32 rectified image,
        ``ivar`` (ncol, nslice) inverse variance from the DRP noise rule
        (or None), and ``bpm`` (ncol, nslice) boolean output mask (True =
        bad).  Axis 0 is the raw detector column (not flipped).
    """
    img, gpm, rows = _check_inputs(image, bpm, matrix)
    nslice, nwin, ncol = matrix.influence.shape
    B = matrix.influence
    blame, fblame, wpos, fwpos = blame_kernels(matrix)
    P = _scatter_operator(rows, img.shape[0])
    # Pixels outside the good-pixel mask (and the padding row) carry no
    # residual
    gpmf = gpm.astype(np.float32)

    # Validity of the +/- stride neighbours (DRP: weight[sp-64][i] > 0)
    has_lo = np.zeros_like(wpos)
    has_hi = np.zeros_like(wpos)
    has_lo[stride:] = wpos[:-stride]
    has_hi[:-stride] = wpos[stride:]

    c = np.zeros((nslice, ncol), dtype=np.float32)
    relax = np.float32(relax)
    for it in range(niter):
        # Model of the raw frame and residual on good pixels
        model = P @ (B * c[:, None, :]).reshape(nslice * nwin, ncol)
        resid = (img - model) * gpmf
        rwin = resid[rows]
        if it < 15:
            # Sharpened blame, accumulated and then applied with the
            # coupling to the spatial neighbours (+/- one lenslet column)
            t = relax * np.sum(rwin * blame, axis=1)
            coef = np.float32(0.4 if it < 10 else -0.2)
            dc = t.copy()
            t_lo = np.zeros_like(t)
            t_hi = np.zeros_like(t)
            t_lo[stride:] = t[:-stride]
            t_hi[:-stride] = t[stride:]
            dc += np.where(has_lo, coef * (t - t_lo), 0.)
            dc += np.where(has_hi, coef * (t - t_hi), 0.)
            c += np.where(wpos, dc, 0.)
        else:
            # Plain back-projection with the final kernel
            c += relax * np.sum(rwin * fblame, axis=1)
        if 11 < it < 18:
            # 5-tap smoothing along the dispersion (interior columns)
            c[:, 2:-2] = 0.1 * c[:, :-4] + 0.2 * c[:, 1:-3] \
                + 0.4 * c[:, 2:-2] + 0.2 * c[:, 3:-1] + 0.1 * c[:, 4:]

    rect = c / np.float32(norm)

    # Output mask: more than half of the final kernel on good pixels
    gfrac = _good_fraction(fblame, gpm, rows)
    good = fwpos & (gfrac > 0.5) & (matrix.effective[:, None] > 0)

    ivar = None
    if noise is not None:
        sig = np.zeros_like(img)
        sig[:-1] = np.where(gpm[:-1], noise, 0.)
        sig_out = np.sum(fblame * sig[rows], axis=1)
        ivar = np.where(good & (sig_out > 0),
                        1. / np.where(sig_out > 0, sig_out, 1.)**2, 0.)
        ivar = ivar.T.astype(np.float32)
    return rect.T, ivar, np.logical_not(good).T


def _band_layout(matrix, nband):
    """
    Assign slices to bands and list the overlapping slice pairs.

    Slice ``s`` belongs to band ``s % nband`` (its lenslet row) and slot
    ``s // nband`` (its lenslet column) within the band.  Two slices are
    coupled when their nonzero profile rows overlap; the normal equations
    are block-tridiagonal if only slices in the same or adjacent bands
    are coupled, which is checked.

    Generated by JXP and Claude.

    Args:
        matrix (:class:`RectMatrix`):
            The rectification matrix.
        nband (:obj:`int`):
            Number of bands.

    Returns:
        :obj:`dict`: Layout with keys ``nband``, ``nslot``, ``band``,
        ``slot``, ``active`` and ``pairs``, a list of ``(d, s, t)`` with
        ``d = bottom[t] - bottom[s] >= 0`` and integer arrays ``s``,
        ``t`` of the coupled slice pairs with that offset.
    """
    nslice = matrix.nslice
    band = np.arange(nslice) % nband
    slot = np.arange(nslice) // nband
    nslot = int(slot.max()) + 1
    active, first, last = matrix.footprint()
    lo = matrix.bottom + first
    hi = matrix.bottom + last
    idx = np.where(active)[0]
    # All overlapping pairs (s <= t by row order) among active slices
    ss, tt = np.meshgrid(idx, idx, indexing='ij')
    keep = (lo[ss] <= hi[tt]) & (lo[tt] <= hi[ss]) & (ss <= tt)
    ss, tt = ss[keep], tt[keep]
    dband = np.abs(band[ss] - band[tt])
    if np.any(dband > 1):
        raise PypeItError('Rectification-matrix geometry is not block '
                          'tridiagonal in lenslet rows; cannot use the '
                          'lstsq solver with nband={0}.'.format(nband))
    # Order every pair so that d = bottom[t] - bottom[s] >= 0
    d = matrix.bottom[tt] - matrix.bottom[ss]
    swap = d < 0
    ss, tt = np.where(swap, tt, ss), np.where(swap, ss, tt)
    d = np.abs(d)
    pairs = [(dd, ss[d == dd], tt[d == dd]) for dd in np.unique(d)
             if dd < matrix.nwin]
    return dict(nband=nband, nslot=nslot, band=band, slot=slot,
                active=active, pairs=pairs)


def _batched_inv(mat):
    """
    Invert a stack of symmetric matrices.

    Generated by JXP and Claude.

    Args:
        mat (`numpy.ndarray`_):
            Array (..., n, n).

    Returns:
        `numpy.ndarray`_: The inverses.
    """
    return np.linalg.inv(mat)


def _shift_blocks(arr, d):
    """
    Shift a stack of per-band blocks along the band axis.

    ``out[s] = arr[s + d]`` where ``0 <= s + d < nb``; zero elsewhere.

    Generated by JXP and Claude.

    Args:
        arr (`numpy.ndarray`_):
            Array (nb, ...) of per-band blocks.
        d (:obj:`int`):
            Band offset.

    Returns:
        `numpy.ndarray`_: The shifted array (a new array).
    """
    out = np.zeros_like(arr)
    nb = arr.shape[0]
    if d >= 0:
        if d < nb:
            out[:nb - d] = arr[d:]
    elif -d < nb:
        out[-d:] = arr[:nb + d]
    return out


def _normal_blocks(B, rows, wgt, lay, couple_bands):
    """
    Diagonal and upper blocks of ``A^T diag(wgt) A`` for a chunk of
    detector columns.

    Generated by JXP and Claude.

    Args:
        B (`numpy.ndarray`_):
            Influence cube of the chunk (nslice, nwin, nx), float64.
        rows (`numpy.ndarray`_):
            Row index (nslice, nwin) into the padded detector rows.
        wgt (`numpy.ndarray`_):
            Pixel weights of the chunk (nrow+1, nx); zero on bad pixels.
        lay (:obj:`dict`):
            Band layout from :func:`_band_layout`.
        couple_bands (:obj:`bool`):
            Keep the blocks coupling adjacent bands.

    Returns:
        :obj:`tuple`: ``D`` and ``U``, each (nb, nx, ns, ns); ``U[r]``
        couples band ``r`` (rows) to band ``r+1`` (columns).
    """
    nb, ns = lay['nband'], lay['nslot']
    band, slot = lay['band'], lay['slot']
    nwin = B.shape[1]
    nx = B.shape[2]
    D = np.zeros((nb, nx, ns, ns))
    U = np.zeros((nb, nx, ns, ns))
    for d, s, t in lay['pairs']:
        # Rows bottom[t] + l for l < nwin - d are shared
        ls = np.arange(d, nwin)
        wv = wgt[rows[s][:, ls]]
        val = np.sum(B[s][:, ls] * B[t][:, :nwin - d] * wv, axis=1)
        rs, rt = band[s], band[t]
        ks, kt = slot[s], slot[t]
        same = rs == rt
        D[rs[same], :, ks[same], kt[same]] = val[same]
        D[rt[same], :, kt[same], ks[same]] = val[same]
        if couple_bands:
            # Adjacent bands: store in U[r] with r the lower index
            up = (rt == rs + 1)
            U[rs[up], :, ks[up], kt[up]] = val[up]
            dn = (rs == rt + 1)
            U[rt[dn], :, kt[dn], ks[dn]] = val[dn]
    return D, U


def _lstsq_core(img, wgt, rows, matrix, lay, var_list=None, solve=True,
                couple_bands=True, chunk=128, band_window=2):
    """
    Weighted least-squares solution and (sandwich) variances.

    For every detector column the normal matrix ``N = A^T W A`` is block
    tridiagonal (one block per band of lenslet rows).  The system
    ``N c = A^T W F`` is solved with a batched block-Thomas algorithm
    (forward Schur complements ``S_r``, backward Schur complements
    ``T_r``).  The diagonal blocks of ``N^-1`` are
    ``G_rr = (S_r + T_r - D_r)^-1``; the off-diagonal blocks of a block
    column follow from ``G_{r,s} = -S_r^-1 U_r G_{r+1,s}`` (``r < s``) and
    ``G_{r,s} = -T_r^-1 U_{r-1}^T G_{r-1,s}`` (``r > s``).  For each true
    pixel variance ``V`` in ``var_list`` the diagonal of the sandwich
    covariance ``N^-1 (A^T W V W A) N^-1`` is accumulated over the
    blocks of ``N^-1`` within ``band_window`` bands of the diagonal
    (the bands are coupled only through the slices at their edges, so
    ``N^-1`` decays very quickly away from the diagonal; the truncation
    is checked in the unit tests).  If ``var_list`` is None, the
    variance is ``diag(N^-1)`` (correct when ``W = V^-1``).

    Generated by JXP and Claude.

    Args:
        img (`numpy.ndarray`_, None):
            Padded image (nrow+1, ncol); not used if ``solve`` is False.
        wgt (`numpy.ndarray`_):
            Padded pixel weights (nrow+1, ncol), zero on bad pixels.
        rows (`numpy.ndarray`_):
            Row index (nslice, nwin).
        matrix (:class:`RectMatrix`):
            The rectification matrix.
        lay (:obj:`dict`):
            Band layout from :func:`_band_layout`.
        var_list (:obj:`list`, optional):
            Padded true pixel variances (nrow+1, ncol).
        solve (:obj:`bool`, optional):
            Compute the solution (otherwise only the variances).
        couple_bands (:obj:`bool`, optional):
            Keep the coupling between adjacent bands.
        chunk (:obj:`int`, optional):
            Number of detector columns processed at once.
        band_window (:obj:`int`, optional):
            Number of bands on either side of the diagonal kept in the
            sandwich variance.

    Returns:
        :obj:`tuple`: The solution ``c`` (nslice, ncol) (None if ``solve``
        is False) and a list of variances (nslice, ncol), one per element
        of ``var_list`` (or ``[diag(N^-1)]``).  Unknowns with no weight
        have zero variance.
    """
    nslice, nwin, ncol = matrix.influence.shape
    nb, ns = lay['nband'], lay['nslot']
    band, slot = lay['band'], lay['slot']
    sandwich = var_list is not None and len(var_list) > 0
    nvar = len(var_list) if sandwich else 1
    R = max(0, int(band_window))

    c_out = np.zeros((nslice, ncol), dtype=np.float64) if solve else None
    var_out = [np.zeros((nslice, ncol), dtype=np.float64)
               for _ in range(nvar)]
    for x0 in range(0, ncol, chunk):
        x1 = min(ncol, x0 + chunk)
        nx = x1 - x0
        B = matrix.influence[:, :, x0:x1].astype(np.float64)
        w = wgt[:, x0:x1]
        D, U = _normal_blocks(B, rows, w, lay, couple_bands)
        # Blocks of A^T W V W A for each true variance
        Mblk = [] if not sandwich else \
            [_normal_blocks(B, rows, w * w * v[:, x0:x1], lay, couple_bands)
             for v in var_list]

        # Unconstrained unknowns (no weight): identity rows, zero rhs
        diag = np.einsum('rxkk->rxk', D).copy()
        dead = diag <= 0
        scale = np.where(dead, 1., diag)
        rr, xx, kk = np.where(dead)
        D[rr, xx, kk, kk] = 1.
        # Tiny ridge for numerical safety
        D[..., np.arange(ns), np.arange(ns)] += 1e-12 * scale

        # Right-hand side A^T W F
        z = None
        if solve:
            y = img[:, x0:x1].astype(np.float64)
            z = np.zeros((nb, nx, ns))
            z[band, :, slot] = np.sum(B * (w * y)[rows], axis=1)

        # Forward sweep: Schur complements S_r and reduced rhs
        Sall = np.zeros_like(D)
        Sinv = np.zeros_like(D)
        for r in range(nb):
            S = D[r].copy()
            if r > 0:
                UtSi = np.matmul(np.swapaxes(U[r - 1], 1, 2), Sinv[r - 1])
                S -= np.matmul(UtSi, U[r - 1])
                if solve:
                    z[r] -= np.einsum('xij,xj->xi', UtSi, z[r - 1])
            Sall[r] = S
            Sinv[r] = _batched_inv(S)
        # Backward sweep: solution, backward Schur complements T_r and
        # diagonal blocks of N^-1
        sol = np.zeros((nb, nx, ns)) if solve else None
        Tinv = np.zeros_like(D)
        Gd = np.zeros_like(D)
        T = D[nb - 1].copy()
        for r in range(nb - 1, -1, -1):
            if r < nb - 1:
                T = D[r] - np.matmul(np.matmul(U[r], Tinv[r + 1]),
                                     np.swapaxes(U[r], 1, 2))
            Tinv[r] = _batched_inv(T)
            if solve:
                zr = z[r] if r == nb - 1 else \
                    z[r] - np.einsum('xij,xj->xi', U[r], sol[r + 1])
                sol[r] = np.einsum('xij,xj->xi', Sinv[r], zr)
            Gd[r] = _batched_inv(Sall[r] + T - D[r])

        if solve:
            c_out[:, x0:x1] = sol[band, :, slot]
        if not sandwich:
            vb = np.einsum('rxkk->rxk', Gd)
            vb[dead] = 0.
            var_out[0][:, x0:x1] = vb[band, :, slot]
            continue

        # Off-diagonal blocks of the block columns of N^-1:
        # Gw[d][s] = G_{s+d, s}
        P = np.matmul(Sinv, U)                       # S_r^-1 U_r
        Q = np.zeros_like(D)
        Q[1:] = np.matmul(Tinv[1:], np.swapaxes(U[:-1], 2, 3))
        Gw = {0: Gd}
        for d in range(1, R + 1):
            Gw[-d] = -np.matmul(_shift_blocks(P, -d), Gw[-d + 1])
            Gw[d] = -np.matmul(_shift_blocks(Q, d), Gw[d - 1])
        for iv, (Dm, Um) in enumerate(Mblk):
            vb = np.zeros((nb, nx, ns))
            UmT = np.swapaxes(Um, 2, 3)
            for d in range(-R, R + 1):
                # Row block r = s + d of M times the block column of N^-1
                Y = np.matmul(_shift_blocks(Dm, d), Gw[d])
                if d + 1 <= R:
                    Y += np.matmul(_shift_blocks(Um, d), Gw[d + 1])
                if d - 1 >= -R:
                    Y += np.matmul(_shift_blocks(UmT, d - 1), Gw[d - 1])
                vb += np.einsum('rxij,rxij->rxj', Gw[d], Y)
            vb[dead] = 0.
            var_out[iv][:, x0:x1] = vb[band, :, slot]
    return c_out, var_out


def _pad_like(arr, img):
    """
    Pad a raw-orientation array with the empty row used by the solvers.

    Generated by JXP and Claude.

    Args:
        arr (`numpy.ndarray`_):
            Array (nrow, ncol).
        img (`numpy.ndarray`_):
            Padded image (nrow+1, ncol) defining the output shape.

    Returns:
        `numpy.ndarray`_: Float64 array (nrow+1, ncol) with a zero last
        row.
    """
    out = np.zeros(img.shape, dtype=np.float64)
    out[:-1] = arr
    return out


def _lstsq_good(matrix, gpm, rows, var):
    """
    Output good-pixel mask of the least-squares solution.

    The DRP rule (more than half of the ``B / sum B`` kernel on good
    pixels) plus a positive, finite variance.

    Generated by JXP and Claude.

    Args:
        matrix (:class:`RectMatrix`):
            The rectification matrix.
        gpm (`numpy.ndarray`_):
            Padded good-pixel mask (nrow+1, ncol).
        rows (`numpy.ndarray`_):
            Row index (nslice, nwin).
        var (`numpy.ndarray`_):
            Variance of the solution (nslice, ncol).

    Returns:
        `numpy.ndarray`_: Boolean (nslice, ncol), True = good.
    """
    _, fblame, _, fwpos = blame_kernels(matrix)
    gfrac = _good_fraction(fblame, gpm, rows)
    return fwpos & (gfrac > 0.5) & (matrix.effective[:, None] > 0) \
        & (var > 0) & np.isfinite(var)


def rectify_lstsq(image, ivar, bpm, matrix, norm=DRP_NORM, nband=NLENS_ROW,
                  couple_bands=True, chunk=128, var=None, band_window=2):
    """
    Extract the lenslet spectra by weighted linear least squares.

    For every detector column ``x`` the model ``F = A c`` (``A`` built
    from the influence cube) is solved exactly in the weighted
    least-squares sense, ``(A^T W A) c = A^T W F`` with ``W = ivar`` on
    good pixels.  Slices are grouped in ``nband`` bands of lenslet rows
    (64 bands of at most 19 slices for OSIRIS); a band is coupled only to
    the adjacent bands (their profiles touch at the band edges), so the
    normal matrix is block tridiagonal and is solved with a batched block
    Thomas algorithm over all columns at once (see :func:`_lstsq_core`).

    Variance: if ``var`` (the true pixel variance) is None, the variance
    of the solution is ``diag((A^T W A)^-1)``, which is correct when the
    weights are the inverse true variance.  Production use (M2 Q&A 1)
    passes *flux-independent* weights in ``ivar`` (read noise plus a
    smoothed background, see :func:`background_variance`) and the true
    variance in ``var``; the variance is then the diagonal of the sandwich
    ``(A^T W A)^-1 A^T W V W A (A^T W A)^-1``.

    The solution and its inverse variance are divided by ``norm`` (and
    multiplied by ``norm**2``) for consistency with the DRP.  The output
    mask follows the DRP rule (more than half of the ``B / sum B`` kernel
    on good pixels), plus slices without any data.

    Generated by JXP and Claude.

    Args:
        image (`numpy.ndarray`_):
            Raw-orientation image (2048 x 2048; dispersion along axis 1).
        ivar (`numpy.ndarray`_, None):
            Pixel weights (inverse variance, or flux-independent weights if
            ``var`` is given).  If None, unit weights are used.
        bpm (`numpy.ndarray`_, None):
            Bad-pixel mask (True = bad); None for no mask.
        matrix (:class:`RectMatrix`):
            The rectification matrix.
        norm (:obj:`float`, optional):
            Normalisation dividing the solution (DRP: 1.28).
        nband (:obj:`int`, optional):
            Number of bands (lenslet rows per lenslet column).
        couple_bands (:obj:`bool`, optional):
            Keep the coupling between adjacent bands (exact solution).  If
            False, each band is solved independently (an approximation,
            kept for diagnostics).
        chunk (:obj:`int`, optional):
            Number of detector columns processed at once (memory control).
        var (`numpy.ndarray`_, optional):
            True pixel variance (same units as ``image`` squared); if
            given, the sandwich variance is returned.
        band_window (:obj:`int`, optional):
            Bands kept on each side of the diagonal in the sandwich
            variance (see :func:`_lstsq_core`).

    Returns:
        :obj:`tuple`: ``rect`` (ncol, nslice) float32 rectified image,
        ``ivar`` (ncol, nslice) float32 inverse variance and ``bpm``
        (ncol, nslice) boolean mask (True = bad).  Axis 0 is the raw
        detector column (not flipped).
    """
    img, gpm, rows = _check_inputs(image, bpm, matrix)
    nrow = image.shape[0]
    # Pixel weights (zero on bad pixels and on the padding row)
    wgt = np.zeros(img.shape, dtype=np.float64)
    if ivar is None:
        wgt[:nrow] = gpm[:nrow]
    else:
        wgt[:nrow] = np.where(gpm[:nrow], ivar, 0.)
    lay = _band_layout(matrix, nband)
    var_list = None if var is None else [_pad_like(var, img)]
    c_out, (var_out,) = _lstsq_core(img, wgt, rows, matrix, lay,
                                    var_list=var_list, solve=True,
                                    couple_bands=couple_bands, chunk=chunk,
                                    band_window=band_window)
    good = _lstsq_good(matrix, gpm, rows, var_out)
    rect = np.where(good, c_out / norm, 0.)
    ivar_out = np.where(good, norm**2 / np.where(good, var_out, 1.), 0.)
    return rect.T.astype(np.float32), ivar_out.T.astype(np.float32), \
        np.logical_not(good).T


def lstsq_variance(weights, bpm, matrix, var_list, norm=DRP_NORM,
                   nband=NLENS_ROW, chunk=128, band_window=2):
    """
    Variance of the least-squares lenslet spectra, without solving.

    Used to give the ``drp`` solution (which converges to the
    least-squares solution) a statistically meaningful variance (M2 Q&A
    3), and to propagate individual variance components (e.g. the read
    noise alone).  For each true pixel variance ``V`` in ``var_list`` the
    diagonal of ``(A^T W A)^-1 A^T W V W A (A^T W A)^-1`` is returned
    (see :func:`_lstsq_core`), divided by ``norm**2``.

    Generated by JXP and Claude.

    Args:
        weights (`numpy.ndarray`_, None):
            Pixel weights (raw orientation); None for unit weights.
        bpm (`numpy.ndarray`_, None):
            Bad-pixel mask (True = bad).
        matrix (:class:`RectMatrix`):
            The rectification matrix.
        var_list (:obj:`list`):
            True pixel variances (raw orientation).
        norm (:obj:`float`, optional):
            Normalisation dividing the solution (DRP: 1.28).
        nband (:obj:`int`, optional):
            Number of bands.
        chunk (:obj:`int`, optional):
            Number of detector columns processed at once.
        band_window (:obj:`int`, optional):
            Bands kept on each side of the diagonal.

    Returns:
        :obj:`tuple`: A list of variances (ncol, nslice), one per element
        of ``var_list`` (zero where undefined), and the boolean output
        mask (ncol, nslice; True = bad) built from the first variance.
    """
    shape = var_list[0].shape
    img, gpm, rows = _check_inputs(np.zeros(shape, dtype=np.float32), bpm,
                                   matrix)
    nrow = shape[0]
    wgt = np.zeros(img.shape, dtype=np.float64)
    if weights is None:
        wgt[:nrow] = gpm[:nrow]
    else:
        wgt[:nrow] = np.where(gpm[:nrow], weights, 0.)
    lay = _band_layout(matrix, nband)
    _, var_out = _lstsq_core(None, wgt, rows, matrix, lay,
                             var_list=[_pad_like(v, img) for v in var_list],
                             solve=False, chunk=chunk,
                             band_window=band_window)
    good = _lstsq_good(matrix, gpm, rows, var_out[0])
    out = [np.where(good, v / norm**2, 0.).T for v in var_out]
    return out, np.logical_not(good).T


def background_variance(image, base_var, bpm=None):
    """
    Flux-independent pixel variance used to weight the least-squares
    rectification (M2 Q&A 1).

    The variance is the flux-independent part of the noise model
    (``base_var``: read noise, dark current, processing variance) plus
    the Poisson variance of a smooth background estimated as the median,
    over the good detector rows, of every raw detector column (the
    background then varies only along the dispersion).  The shot noise of
    compact sources is deliberately left out: down-weighting the bright
    core of a point source moves flux because of the residual error of
    the Keck PSF model (M2 report, section 5.1).

    Generated by JXP and Claude.

    Args:
        image (`numpy.ndarray`_):
            Raw-orientation image (rows x columns) in counts (e-).
        base_var (`numpy.ndarray`_, :obj:`float`):
            Flux-independent variance (e-^2), same shape as ``image`` or a
            scalar.
        bpm (`numpy.ndarray`_, optional):
            Bad-pixel mask (True = bad) excluded from the medians.

    Returns:
        `numpy.ndarray`_: The weighting variance (same shape as ``image``).
    """
    img = np.ma.MaskedArray(np.clip(image, 0., None),
                            mask=None if bpm is None
                            else np.asarray(bpm, dtype=bool))
    bkg = np.ma.median(img, axis=0).filled(0.)
    return np.broadcast_to(base_var, image.shape) + bkg[None, :]


def subtract_reference_rows(image, rows=(2032, 2045)):
    """
    Remove column offsets measured on unilluminated detector rows.

    The OSIRIS DRP ("Adjust Channel Levels", H2RG branch) subtracts from
    every column the median of rows 2032-2044 (the top rows of the
    detector, below the reference pixels, which receive no light) to
    remove the 60 Hz pattern noise.  Input and output are in the raw
    orientation.

    Generated by JXP and Claude.

    Args:
        image (`numpy.ndarray`_):
            Raw-orientation image (rows x columns).
        rows (:obj:`tuple`, optional):
            First and last+1 row of the unilluminated strip.

    Returns:
        `numpy.ndarray`_: The corrected image (a new array).
    """
    med = np.median(image[rows[0]:rows[1], :], axis=0)
    return image - med[None, :]


def is_broadband(filt):
    """
    Return True for a broadband OSIRIS filter (``Zbb``, ``Kcb``, ...).

    Uses the DRP rule: the third character of the name is ``'b'``.

    Generated by JXP and Claude.

    Args:
        filt (:obj:`str`):
            Filter name.

    Returns:
        :obj:`bool`: True for broadband filters.
    """
    return len(filt) > 2 and filt[2] == 'b'


def narrowband_split(filt, nslice=1216):
    """
    Map rectified slices to lenslets, following ``assembcube_000.pro``.

    - Broadband (``Zbb``, ``Jbb``, ``Hbb``, ``Kbb``, ``Kcb``): identity,
      slice ``sp`` -> cube (row, col) = (``sp % 64``, ``sp // 64``) of a
      64 x 19 cube; the Keck coefficients are at (row + 1, col + 16).
    - Narrowband: only slices 0-1023 are used and each carries up to four
      lenslet spectra head to tail along the detector row: blocks
      (row, col) = (``sp % 64 + 2``, ``sp // 64 + 3``),
      (``sp % 64 + 1``, ``sp // 64 + 19``), (``sp % 64``, ``sp // 64 +
      35``) and, for ``sp > 831``, (``min(sp % 64 + 3, 65)``,
      ``sp // 64 - 13``) of a 66 x 51 cube, which is also the grid of
      the Keck coefficients.

    The (row, col) positions are those of the DRP cube *before* the Keck I
    flip of the row axis.

    Generated by JXP and Claude.

    Args:
        filt (:obj:`str`):
            Filter name (header ``SFILTER``).
        nslice (:obj:`int`, optional):
            Number of slices in the rectification matrix.

    Returns:
        `astropy.table.Table`_: One row per (slice, lenslet) with columns
        ``slice``, ``block`` (0-2, or 3 for the ``sp > 831`` extras),
        ``row``/``col`` (cube position) and ``crow``/``ccol`` (index in
        the Keck coefficient array).  ``meta`` holds ``nrows``,
        ``ncols`` and ``broadband``.
    """
    if is_broadband(filt):
        sp = np.arange(nslice)
        row, col = sp % NLENS_ROW, sp // NLENS_ROW
        tbl = Table(dict(slice=sp, block=np.zeros_like(sp), row=row,
                         col=col, crow=row + 1, ccol=col + 16))
        tbl.meta.update(nrows=64, ncols=int(col.max()) + 1, broadband=True)
        return tbl
    nrows, ncols = 66, 51
    sp = np.arange(min(nslice, 1024))
    r, q = sp % (nrows - 2), sp // (nrows - 2)
    out = dict(slice=[], block=[], row=[], col=[])
    # Three blocks of 16 x 64 lenslets, head to tail on the detector
    for blk, (drow, dcol) in enumerate([(2, 3), (1, 19), (0, 35)]):
        out['slice'].append(sp)
        out['block'].append(np.full(sp.size, blk))
        out['row'].append(r + drow)
        out['col'].append(q + dcol)
    # A few extra spectra in the lowest lenslet columns
    ext = sp > 831
    out['slice'].append(sp[ext])
    out['block'].append(np.full(ext.sum(), 3))
    out['row'].append(np.minimum(r[ext] + 3, nrows - 1))
    out['col'].append(q[ext] - 16 + 3)
    tbl = Table({k: np.concatenate(v) for k, v in out.items()})
    tbl['crow'] = tbl['row']
    tbl['ccol'] = tbl['col']
    tbl.meta.update(nrows=nrows, ncols=ncols, broadband=False)
    return tbl


def cosmic_mask_drp2016(frame):
    """
    Cosmic-ray flagging of the September 2016 Keck OSIRIS DRP.

    Port of ``cleancosmic_000.pro`` at OsirisDRP commit 9f11afd (the
    version that produced the 2016 reference cubes; the module has been
    skipped for H2RG data since 2017-09).  Two passes over 100-pixel
    strips of each detector row: a pixel is flagged when its absolute
    value exceeds 1.2 times the sum of its two neighbours, each floored at
    3 sigma (robust standard deviation of the strip).  Intended for A-B
    differences; on a single frame it flags the cores of sharp OH lines.

    Generated by JXP and Claude.

    Args:
        frame (`numpy.ndarray`_):
            Raw-orientation image (2048 x 2048).

    Returns:
        :obj:`tuple`: The image with flagged pixels set to 0 and the
        boolean mask of flagged pixels.
    """
    img = np.array(frame, dtype=np.float32, copy=True)
    qual = np.full(img.shape, 9, dtype=np.int16)
    nrow = img.shape[0]
    indx = np.arange(100)
    lft, rgt = np.maximum(0, indx - 1), np.minimum(99, indx + 1)
    for _ in range(2):
        for ii in range(0, img.shape[1] - 100, 97):
            strip = img[:, ii:ii + 100].astype(float)
            ok = qual[:, ii:ii + 100] == 9
            nok = ok.sum(axis=1)
            std = np.zeros(nrow)
            full = nok == 100
            if np.any(full):
                srt = np.sort(strip[full], axis=1)[:, 10:91]
                std[full] = srt.std(axis=1, ddof=1)
            for j in np.where(~full & (nok > 20))[0]:
                isok = np.where(ok[j])[0]
                # (sic) indices of the sorted good subset applied to the
                # full strip, as in the IDL code
                q = np.argsort(strip[j, isok], kind='stable')
                q = q[10:q.size - 9]
                std[j] = strip[j, q].std(ddof=1)
            comp = np.where(ok, np.maximum(np.abs(strip), 3 * std[:, None]),
                            3 * std[:, None])
            rat = np.abs(strip) / (comp[:, lft] + comp[:, rgt])
            upd = qual[:, ii + 1:ii + 99] * (rat[:, 1:99] <= 1.2)
            proc = nok > 20
            qual[proc, ii + 1:ii + 99] = upd[proc]
        img[qual != 9] = 0.
    return img, qual != 9


def keck_order(filt):
    """
    Grating order of an OSIRIS filter (DRP rule on the minimum
    wavelength: K 3, H 4, J 5, Z 6).

    Generated by JXP and Claude.

    Args:
        filt (:obj:`str`):
            Filter name.

    Returns:
        :obj:`int`: The grating order.
    """
    return drp_wavelength_grid(filt)[1]


def keck_pixels(lam, coeffs, order, frac=1.0):
    """
    Detector column of a wavelength from the Keck coefficients.

    ``x = poly(lam * order / 3 / frac - 2200, coeffs)`` (nm, vacuum).

    Generated by JXP and Claude.

    Args:
        lam (:obj:`float`, `numpy.ndarray`_):
            Vacuum wavelength(s) in nm; must broadcast against the leading
            dimensions of ``coeffs``.
        coeffs (`numpy.ndarray`_):
            Polynomial coefficients (..., 4), lowest order first.
        order (:obj:`int`):
            Grating order.
        frac (:obj:`float`, optional):
            Grating expansion factor (1 for no temperature correction).

    Returns:
        `numpy.ndarray`_: Raw detector column(s).
    """
    lam_s = np.asarray(lam, dtype=float) * order / 3. / frac - DRP_MIDWAVE
    c = np.moveaxis(np.asarray(coeffs, dtype=float), -1, 0)
    # Trailing axes of lam beyond those of the coefficients broadcast
    extra = lam_s.ndim - (c.ndim - 1)
    if extra > 0:
        c = c.reshape(c.shape + (1,) * extra)
    return np.polynomial.polynomial.polyval(lam_s, c, tensor=False)


def keck_wavelengths(coeffs, order, frac=1.0, ncol=2048, step=0.05,
                     half_range=600.):
    """
    Invert the Keck pixel(wavelength) relation for a set of lenslets.

    The Keck coefficients give the detector column as a cubic in the
    scaled wavelength ``lam' = lam * order / 3 / frac - 2200`` nm.  The
    relation is sampled on a fine ``lam'`` grid and inverted by linear
    interpolation over its monotonic (decreasing) branch, giving the
    vacuum wavelength at every raw detector column.

    Generated by JXP and Claude.

    Args:
        coeffs (`numpy.ndarray`_):
            Coefficients (nlens, 4).
        order (:obj:`int`):
            Grating order.
        frac (:obj:`float`, optional):
            Grating expansion factor.
        ncol (:obj:`int`, optional):
            Number of detector columns.
        step (:obj:`float`, optional):
            Sampling of the scaled wavelength grid (nm).
        half_range (:obj:`float`, optional):
            Half width of the scaled wavelength grid (nm).

    Returns:
        `numpy.ndarray`_: Vacuum wavelengths (nm), shape (nlens, ncol),
        indexed by the raw detector column (wavelength *decreases* with
        column).
    """
    c = np.atleast_2d(np.asarray(coeffs, dtype=float))
    lam_s = np.arange(-half_range, half_range + step, step)
    xcol = np.arange(ncol, dtype=float)
    out = np.zeros((c.shape[0], ncol), dtype=float)
    for i in range(c.shape[0]):
        x = np.polynomial.polynomial.polyval(lam_s, c[i])
        # Monotonic (decreasing) branch around the detector centre
        dec = np.diff(x) < 0
        k0 = int(np.argmin(np.abs(x - ncol / 2.)))
        k0 = min(k0, dec.size - 1)
        lo = k0
        while lo > 0 and dec[lo - 1]:
            lo -= 1
        hi = k0
        while hi < dec.size - 1 and dec[hi + 1]:
            hi += 1
        xs, ls = x[lo:hi + 2][::-1], lam_s[lo:hi + 2][::-1]
        # Linear interpolation, linear extrapolation beyond the branch
        out[i] = _idl_interpol(ls, xs, xcol)
    return (out + DRP_MIDWAVE) * 3. * frac / order


def lenslet_layout(filt, coeffs, frac=1.0, nslice=1216, ncol=2048,
                   nrow_block=NLENS_ROW, valid_thresh=100.):
    """
    Layout of the "lenslet image" built from a rectified OSIRIS frame.

    The rectified frame has one row per matrix slice; a broadband slice
    holds one lenslet spectrum, a narrowband slice up to four short
    spectra of different lenslets head to tail (see
    :func:`narrowband_split`).  PypeIt instead works on an image with one
    spatial pixel per *lenslet*: lenslet ``(crow, ccol)`` of the Keck
    66 x 51 grid occupies spatial pixel ``pos = 64 * bidx + slice % 64``,
    where ``bidx`` indexes the Keck lenslet columns present for the
    filter (one block of 64 lenslets per column).  Its spectrum is copied
    from its slice over a window of raw detector columns ``[xlo, xhi]``:
    for broadband filters the columns covering the filter band (DRP
    wavelength grid), and for narrowband filters the same extended
    halfway into the gaps to the neighbouring spectra of the same slice.
    For broadband filters the layout is the identity (``pos = slice``).

    Lenslets without Keck coefficients (``coeffs[crow, ccol, 0] <=
    valid_thresh``, i.e. outside the field) are dropped, as are the
    narrowband "extra" spectra that the DRP clips onto row 65.

    Generated by JXP and Claude.

    Args:
        filt (:obj:`str`):
            Filter name.
        coeffs (`numpy.ndarray`_):
            Keck wavelength coefficients (66, 51, 4).
        frac (:obj:`float`, optional):
            Grating expansion factor.
        nslice (:obj:`int`, optional):
            Number of slices of the rectification matrix.
        ncol (:obj:`int`, optional):
            Number of detector columns.
        nrow_block (:obj:`int`, optional):
            Lenslets per block (lenslet rows per column).
        valid_thresh (:obj:`float`, optional):
            Minimum constant coefficient of a valid lenslet (DRP rule).

    Returns:
        `astropy.table.Table`_: One row per lenslet with columns
        ``slice``, ``block`` (narrowband split block), ``crow``/``ccol``
        (Keck grid), ``lens_id`` (``crow * 51 + ccol``), ``name``
        (``L<ccol>_<crow>``), ``bidx`` (block of the lenslet image),
        ``pos`` (spatial pixel), ``xlo``/``xhi`` (raw-column window,
        inclusive) and ``xcen`` (raw column of the band centre).  ``meta``
        holds ``nblock``, ``nspat``, ``block_cols`` (Keck column of each
        block), ``broadband``, ``filter`` and ``ncol``.
    """
    c = np.asarray(coeffs, dtype=float)
    ngrid_col = c.shape[1]
    tbl = narrowband_split(filt, nslice=nslice)
    broadband = bool(tbl.meta['broadband'])
    nrows = c.shape[0]
    row = tbl['slice'] % nrow_block
    # Drop the narrowband extras that the DRP clips onto the last row
    keep = np.ones(len(tbl), dtype=bool)
    if not broadband:
        keep &= np.logical_not((tbl['block'] == 3)
                               & (row + 3 > nrows - 1))
    keep &= c[tbl['crow'], tbl['ccol'], 0] > valid_thresh
    tbl = tbl[keep]
    row = tbl['slice'] % nrow_block
    # One block per Keck lenslet column present
    block_cols = np.unique(tbl['ccol'])
    tbl['bidx'] = np.searchsorted(block_cols, tbl['ccol'])
    tbl['pos'] = nrow_block * tbl['bidx'] + row
    if len(np.unique(tbl['pos'])) != len(tbl):
        raise PypeItError('Lenslet layout is not unique; check the '
                          'narrowband split.')
    tbl['lens_id'] = tbl['crow'] * ngrid_col + tbl['ccol']
    tbl['name'] = [f'L{cc:02d}_{rr:02d}'
                   for cc, rr in zip(tbl['ccol'], tbl['crow'])]
    order = keck_order(filt)
    cl = c[tbl['crow'], tbl['ccol']]
    minl, npix, disp = DRP_FILTER_GRID[filt]
    lam_blue, lam_red = minl, minl + (npix - 1) * disp
    # Wavelength decreases with column: the blue end has the larger x
    x_blue = keck_pixels(np.full(len(tbl), lam_blue), cl, order, frac)
    x_red = keck_pixels(np.full(len(tbl), lam_red), cl, order, frac)
    tbl['xcen'] = 0.5 * (x_blue + x_red)
    xlo = np.zeros(len(tbl), dtype=int)
    xhi = np.full(len(tbl), ncol - 1, dtype=int)
    if broadband:
        # Only the filter band (the DRP cube range) receives light; the
        # rest of the row is masked (no flux, and a step at the filter
        # edges that confuses line finding and sky models)
        xlo = np.clip(np.ceil(x_red), 0, ncol - 1).astype(int)
        xhi = np.clip(np.floor(x_blue), 0, ncol - 1).astype(int)
    else:
        lo_b = x_red.copy()
        hi_b = x_blue.copy()
        # Half of the typical gap between consecutive spectra of a slice
        gaps = []
        for sp in np.unique(tbl['slice']):
            idx = np.where(tbl['slice'] == sp)[0]
            idx = idx[np.argsort(tbl['xcen'][idx])]
            gaps += list(x_red[idx[1:]] - x_blue[idx[:-1]])
        gaps = np.asarray(gaps)
        if gaps.size > 0 and np.any(gaps < 0):
            log.warning(f'{np.sum(gaps < 0)} narrowband spectra overlap '
                        'their neighbours on the detector; splitting at '
                        'the midpoints.')
        half = 0.5 * np.median(gaps) if gaps.size > 0 else 40.
        for sp in np.unique(tbl['slice']):
            idx = np.where(tbl['slice'] == sp)[0]
            idx = idx[np.argsort(tbl['xcen'][idx])]
            lo = lo_b[idx] - half
            hi = hi_b[idx] + half
            # Split shared gaps at their midpoints
            mid = 0.5 * (x_blue[idx[:-1]] + x_red[idx[1:]])
            hi[:-1] = np.minimum(hi[:-1], mid)
            lo[1:] = np.maximum(lo[1:], mid)
            xlo[idx] = np.clip(np.ceil(lo), 0, ncol - 1).astype(int)
            xhi[idx] = np.clip(np.floor(hi), 0, ncol - 1).astype(int)
            # Guarantee disjoint integer windows
            xlo[idx[1:]] = np.maximum(xlo[idx[1:]], xhi[idx[:-1]] + 1)
    tbl['xlo'] = xlo
    tbl['xhi'] = xhi
    tbl.meta.update(nblock=len(block_cols), nspat=nrow_block * len(block_cols),
                    block_cols=list(block_cols), broadband=broadband,
                    filter=filt, ncol=ncol, nrow_block=nrow_block)
    return tbl


def block_reference(layout):
    """
    Reference lenslet of every block of a lenslet layout.

    The reference is the lenslet closest to the middle of the block (row
    ``nrow_block // 2``); the per-block wavelength solution follows it and
    the other lenslets are corrected relative to it.

    Generated by JXP and Claude.

    Args:
        layout (`astropy.table.Table`_):
            Output of :func:`lenslet_layout`.

    Returns:
        `numpy.ndarray`_: Row index into ``layout`` of the reference
        lenslet of each block (``nblock``,).
    """
    nrb = layout.meta['nrow_block']
    ref = np.zeros(layout.meta['nblock'], dtype=int)
    inblock = np.asarray(layout['pos']) % nrb
    for b in range(layout.meta['nblock']):
        idx = np.where(layout['bidx'] == b)[0]
        ref[b] = idx[np.argmin(np.abs(inblock[idx] - nrb // 2))]
    return ref


def lenslet_band_mask(lam, layout, filt=None):
    """
    Pixels of every lenslet spectrum that receive light through the filter.

    A pixel is used when it lies inside the lenslet's raw-column window
    (``xlo``/``xhi`` of :func:`lenslet_layout`) and its wavelength inside
    the filter band (the DRP wavelength grid of the filter).

    Generated by JXP and Claude.

    Args:
        lam (`numpy.ndarray`_):
            Wavelengths (nm) of every lenslet, shape (nlenslet, ncol),
            indexed by the *raw* detector column (see
            :func:`keck_wavelengths`).
        layout (`astropy.table.Table`_):
            Output of :func:`lenslet_layout`.
        filt (:obj:`str`, optional):
            Filter name; defaults to ``layout.meta['filter']``.

    Returns:
        `numpy.ndarray`_: Boolean array with the shape of ``lam`` (raw
        column order).
    """
    _filt = layout.meta['filter'] if filt is None else filt
    minl, npix, disp = DRP_FILTER_GRID[_filt]
    x = np.arange(lam.shape[1])[None, :]
    inwin = (x >= np.asarray(layout['xlo'])[:, None]) \
        & (x <= np.asarray(layout['xhi'])[:, None])
    return inwin & (lam >= minl) & (lam <= minl + (npix - 1) * disp)


def lenslet_block_tilts(lam, layout, order=(6, 4)):
    """
    Tilts of the lenslet image derived from the Keck wavelength solutions.

    Every block of the lenslet image (one Keck lenslet column; see
    :func:`lenslet_layout`) shares the wavelength solution of its reference
    lenslet (:func:`block_reference`).  The lenslets of a block are
    staggered by ~1.9 pixels per lenslet row and their dispersions differ,
    so a wavelength ``lambda_p(x)`` of lenslet ``p`` at spectral pixel
    ``x`` corresponds to the reference-lenslet pixel ``t = lambda_ref^-1(
    lambda_p(x))``.  PypeIt's tilts are exactly this mapping, normalised by
    ``nspec - 1``: the wavelength image is ``wave_ref(tilts)``.  This
    function fits ``t / (nspec - 1)`` of every block with a 2D Legendre
    polynomial in ``(x / (nspec - 1), spat / (nspat - 1))`` (the convention
    of :func:`pypeit.core.tracewave.fit2tilts`), using the pixels inside the
    filter band (:func:`lenslet_band_mask`).  The per-lenslet residual is
    left to the per-lenslet wavelengths of the Fiber pypeline.

    Generated by JXP and Claude.

    Args:
        lam (`numpy.ndarray`_):
            Wavelengths (nm) of every lenslet of ``layout``, shape
            (nlenslet, ncol), indexed by the *raw* detector column
            (wavelength decreasing with column).
        layout (`astropy.table.Table`_):
            Output of :func:`lenslet_layout`.
        order (:obj:`tuple`, optional):
            Legendre orders in the spectral and spatial directions.

    Returns:
        :obj:`tuple`: ``coeffs`` (order[0]+1, order[1]+1, nblock) with the
        Legendre coefficients of each block, and ``resid``, a float array
        with the shape of ``lam`` (spectral axis flipped, i.e. ordered by
        PypeIt spectral pixel) holding the fit residual in pixels (model -
        exact) inside the band and NaN elsewhere.
    """
    # PypeIt orientation: wavelength increasing with spectral pixel
    lamf = np.asarray(lam, dtype=float)[:, ::-1]
    band = lenslet_band_mask(lam, layout)[:, ::-1]
    nlens, nspec = lamf.shape
    nspat = layout.meta['nspat']
    xnorm, snorm = float(nspec - 1), float(nspat - 1)
    x = np.arange(nspec, dtype=float)
    ref = block_reference(layout)
    nblock = layout.meta['nblock']
    coeffs = np.zeros((order[0] + 1, order[1] + 1, nblock), dtype=float)
    resid = np.full(lamf.shape, np.nan, dtype=float)
    for b in range(nblock):
        idx = np.where(layout['bidx'] == b)[0]
        lref = lamf[ref[b]]
        # Exact tilt of every lenslet: reference pixel at its wavelengths
        tval = np.array([np.interp(lamf[i], lref, x) for i in idx])
        ok = band[idx] & (lamf[idx] >= lref[0]) & (lamf[idx] <= lref[-1])
        if not np.any(ok):
            # Unusable block: identity tilts
            coeffs[0, 0, b] = coeffs[1, 0, b] = 0.5
            continue
        spat = np.repeat(np.asarray(layout['pos'][idx], dtype=float)[:, None],
                         nspec, axis=1)
        xx = np.tile(x, (len(idx), 1))
        fit = fitting.PypeItFit(xval=xx[ok] / xnorm, x2=spat[ok] / snorm,
                                yval=tval[ok] / xnorm, func='legendre2d',
                                order=np.atleast_1d(order), minx=0.,
                                maxx=1., minx2=0., maxx2=1.)
        fit.fit()
        coeffs[:, :, b] = fit.fitc
        model = fit.eval(xx[ok] / xnorm, x2=spat[ok] / snorm) * xnorm
        res = np.full(tval.shape, np.nan)
        res[ok] = model - tval[ok]
        resid[idx] = res
    return coeffs, resid


def lenslet_image(rect, layout, rect_extra=None, bpm=None):
    """
    Map a rectified frame onto the lenslet image (one column per lenslet).

    Generated by JXP and Claude.

    Args:
        rect (`numpy.ndarray`_):
            Rectified frame (ncol, nslice) in the raw column order.
        layout (`astropy.table.Table`_):
            Output of :func:`lenslet_layout`.
        rect_extra (:obj:`list`, optional):
            Further (ncol, nslice) arrays mapped the same way (e.g.
            variances).
        bpm (`numpy.ndarray`_, optional):
            Rectified mask (ncol, nslice), True = bad.

    Returns:
        :obj:`tuple`: The lenslet image (ncol, nspat), the list of mapped
        ``rect_extra`` arrays, and the boolean mask (ncol, nspat), True
        for pixels outside every lenslet window or flagged in ``bpm``.
        Axis 0 is still the raw detector column.
    """
    ncol = rect.shape[0]
    nspat = layout.meta['nspat']
    xcol = np.arange(ncol)[:, None]
    inwin = (xcol >= np.asarray(layout['xlo'])[None, :]) \
        & (xcol <= np.asarray(layout['xhi'])[None, :])
    sl = np.asarray(layout['slice'])
    pos = np.asarray(layout['pos'])

    def _map(arr):
        out = np.zeros((ncol, nspat), dtype=arr.dtype)
        out[:, pos] = np.where(inwin, arr[:, sl], 0)
        return out

    img = _map(rect)
    extra = [] if rect_extra is None else [_map(a) for a in rect_extra]
    good = np.zeros((ncol, nspat), dtype=bool)
    good[:, pos] = inwin if bpm is None \
        else inwin & np.logical_not(bpm[:, sl])
    return img, extra, np.logical_not(good)


def _idl_interpol(v, x, u):
    """
    Linear interpolation with linear extrapolation (IDL ``interpol``).

    Generated by JXP and Claude.

    Args:
        v (`numpy.ndarray`_):
            Values at ``x``.
        x (`numpy.ndarray`_):
            Increasing abscissae (at least two).
        u (`numpy.ndarray`_):
            New abscissae.

    Returns:
        `numpy.ndarray`_: Interpolated values.
    """
    i = np.clip(np.searchsorted(x, u, side='right') - 1, 0, x.size - 2)
    x0, x1 = x[i], x[i + 1]
    return v[i] + (v[i + 1] - v[i]) * (u - x0) / (x1 - x0)


def drp_grating_expansion(tmatemp, cte_temp=None, cte=None):
    """
    Grating expansion factor exactly as computed by the DRP.

    ``(1 + cte(T)) / (1 + cte(50.73 K))`` with IDL ``interpol`` semantics
    (linear *extrapolation* outside the 45-90 K table).  A missing
    ``DTMP7`` reads as 0 K in the DRP (``sxpar`` returns 0), which is
    reproduced when ``tmatemp`` is None.

    Generated by JXP and Claude.

    Args:
        tmatemp (:obj:`float`, None):
            TMA temperature (K, header ``DTMP7``); None means missing.
        cte_temp, cte (`numpy.ndarray`_, optional):
            The aluminium CTE table (temperature in K and CTE).  If None,
            the table shipped with PypeIt (``al_cte.ecsv``) is used.

    Returns:
        :obj:`float`: The expansion factor (wavelengths are divided by
        it).
    """
    if cte_temp is None or cte is None:
        tbl = Table.read(dataPaths.spectrographs.get_file_path(
            'keck_osiris/al_cte.ecsv'), format='ascii.ecsv')
        cte_temp, cte = np.asarray(tbl['temp'], dtype=float), \
            np.asarray(tbl['cte'], dtype=float)
    srt = np.argsort(cte_temp)
    tt, cc = np.asarray(cte_temp)[srt], np.asarray(cte)[srt]
    if tmatemp is None:
        log.warning('DTMP7 missing: reproducing the DRP, which reads it as '
                    '0 K and extrapolates the CTE table.')
        tmatemp = 0.
    cotemp = _idl_interpol(cc, tt, np.atleast_1d(float(tmatemp)))[0]
    coref = _idl_interpol(cc, tt, np.atleast_1d(DRP_NOMINAL_TEMP))[0]
    return float((1 + cotemp) / (1 + coref))


def drp_wavelength_grid(filt):
    """
    Regular wavelength grid (nm, vacuum) of the DRP cube for a filter.

    Generated by JXP and Claude.

    Args:
        filt (:obj:`str`):
            Filter name.

    Returns:
        :obj:`tuple`: The wavelength array (nm) and the grating order used
        to scale it to the 3rd-order reference of the Keck polynomials.
    """
    if filt not in DRP_FILTER_GRID:
        raise PypeItError(f'Unknown OSIRIS filter {filt}.')
    minl, npix, disp = DRP_FILTER_GRID[filt]
    order = 3
    if minl < 1900.:
        order = 4
    if minl < 1450.:
        order = 5
    if minl < 1160.:
        order = 6
    return disp * np.arange(npix) + minl, order


def drp_complete_lenslets(filt, coeffs, lam_scaled, ncol=2048):
    """
    Lenslets whose whole DRP wavelength range falls on the detector.

    Reproduces the ``complete`` array of ``assembcube_000.pro``, including
    the hard-coded broadband (and ``Zn2``-``Zn5``) field masks.

    Generated by JXP and Claude.

    Args:
        filt (:obj:`str`):
            Filter name.
        coeffs (`numpy.ndarray`_):
            Keck coefficients ``coeffs[row, col, :]`` (66 x 51 x 4).
        lam_scaled (`numpy.ndarray`_):
            Grid wavelengths scaled to the reference (``lambda * order / 3
            / frac_expan - 2200``).
        ncol (:obj:`int`, optional):
            Number of detector columns.

    Returns:
        `numpy.ndarray`_: Boolean array (66, 51) indexed [row, col].
    """
    c = np.asarray(coeffs, dtype=float)
    first_pix = np.polynomial.polynomial.polyval(lam_scaled[-1],
                                                 np.moveaxis(c, -1, 0))
    last_pix = np.polynomial.polynomial.polyval(lam_scaled[0],
                                                np.moveaxis(c, -1, 0))
    comp = (c[..., 0] > 100.) & (first_pix >= 0.) & (last_pix <= ncol - 1)
    # The DRP indexes complete[col, row]; here [row, col]
    if is_broadband(filt) or filt[:3] in ['Zn2', 'Zn3']:
        comp[:, 0:16] = False
        comp[:, 35:] = False
    if is_broadband(filt) or filt[:3] in ['Zn2', 'Zn3', 'Zn4', 'Zn5']:
        comp[:, 0:16] = False
        comp[17:, 16] = False
        comp[33:, 17] = False
        comp[49:, 18] = False
    if is_broadband(filt) or filt[:3] in ['Zn2', 'Zn3']:
        comp[0:17, 32] = False
        comp[0:33, 33] = False
        comp[0:49, 34] = False
    return comp


def resample_to_drp_grid(rect, matrix, filt, coeffs, dtmp7, rect_bpm=None,
                         keck1_flip=True, cte_temp=None, cte=None):
    """
    Resample rectified slices onto the DRP cube (for comparisons only).

    Follows ``assembcube_000.pro``: each lenslet spectrum is linearly
    interpolated (good pixels only, linear extrapolation) at the detector
    pixels ``x(lambda) = poly(lambda * order / 3 / frac_expan - 2200,
    coeffs[row, col])`` of the regular DRP wavelength grid; only
    "complete" lenslets are filled; the row axis is flipped for Keck I
    data (all H2RG data).

    Generated by JXP and Claude.

    Args:
        rect (`numpy.ndarray`_):
            Rectified image (ncol, nslice) from :func:`rectify_drp` or
            :func:`rectify_lstsq` (raw column order).
        matrix (:class:`RectMatrix`):
            The rectification matrix (only ``nslice`` is used).
        filt (:obj:`str`):
            Filter name.
        coeffs (`numpy.ndarray`_):
            Epoch-matched Keck coefficients ``coeffs[row, col, :]``
            (e.g. from ``KeckOSIRISSpectrograph.load_wave_coeffs``).
        dtmp7 (:obj:`float`, None):
            TMA temperature (K).  None reproduces the DRP behaviour for a
            missing ``DTMP7`` card (see :func:`drp_grating_expansion`).
        rect_bpm (`numpy.ndarray`_, optional):
            Bad-pixel mask of ``rect`` (True = bad).
        keck1_flip (:obj:`bool`, optional):
            Flip the lenslet-row axis (DRP behaviour for Keck I data).
        cte_temp, cte (`numpy.ndarray`_, optional):
            CTE table; see :func:`drp_grating_expansion`.

    Returns:
        :obj:`tuple`: ``cube`` (ncols, nrows, nwave) float array in the
        numpy order of the DRP FITS cube, ``cube_gpm`` (same shape) good
        voxels, ``filled`` (ncols, nrows) spaxels that received a
        spectrum, and ``wave`` (nwave,) the vacuum wavelengths (nm).
    """
    ncol_det, nslice = rect.shape
    if nslice != matrix.nslice:
        raise PypeItError('Rectified image does not match the matrix.')
    wave, order = drp_wavelength_grid(filt)
    frac = drp_grating_expansion(dtmp7, cte_temp=cte_temp, cte=cte)
    lam_s = wave * order / 3. / frac - DRP_MIDWAVE
    comp = drp_complete_lenslets(filt, coeffs, lam_s, ncol=ncol_det)
    tbl = narrowband_split(filt, nslice=nslice)
    nrows, ncols = tbl.meta['nrows'], tbl.meta['ncols']
    cube = np.zeros((ncols, nrows, wave.size), dtype=float)
    cgpm = np.zeros(cube.shape, dtype=bool)
    filled = np.zeros((ncols, nrows), dtype=bool)
    gpm = np.ones(rect.shape, dtype=bool) if rect_bpm is None \
        else np.logical_not(rect_bpm)
    absc = np.arange(ncol_det, dtype=float)
    c = np.asarray(coeffs, dtype=float)
    for sp, row, col, crow, ccol in zip(tbl['slice'], tbl['row'],
                                        tbl['col'], tbl['crow'],
                                        tbl['ccol']):
        if not comp[crow, ccol]:
            continue
        pix = np.polynomial.polynomial.polyval(lam_s, c[crow, ccol])
        good = gpm[:, sp]
        if good.sum() > 1:
            cube[col, row] = _idl_interpol(rect[good, sp], absc[good], pix)
        # Quality: interpolated 9/0 flag must stay 9 (DRP)
        q = _idl_interpol(np.where(good, 9., 0.), absc, pix)
        cgpm[col, row] = np.isclose(q, 9.)
        filled[col, row] = True
    if keck1_flip:
        cube, cgpm, filled = cube[:, ::-1], cgpm[:, ::-1], filled[:, ::-1]
    return cube, cgpm, filled, wave


def _shift_axis(arr, shift, axis):
    """
    Shift an array along one axis by linear interpolation.

    ``out[i] = arr(i - shift)``, with NaN where the sampled position falls
    outside ``[0, n-1]`` (IDL ``interpolate`` with ``MISSING``).

    Generated by JXP and Claude.

    Args:
        arr (`numpy.ndarray`_):
            Input array.
        shift (:obj:`float`):
            Shift in pixels.
        axis (:obj:`int`):
            Axis to shift.

    Returns:
        `numpy.ndarray`_: The shifted array (float).
    """
    a = np.moveaxis(np.asarray(arr, dtype=float), axis, 0)
    n = a.shape[0]
    x = np.arange(n) - shift
    i0 = np.clip(np.floor(x).astype(int), 0, n - 2)
    f = (x - i0).reshape((-1,) + (1,) * (a.ndim - 1))
    out = (1 - f) * a[i0] + f * a[i0 + 1]
    out[(x < 0) | (x > n - 1)] = np.nan
    return np.moveaxis(out, 0, axis)


def drp_correct_dispersion(cube, wave, elevation, parang, pa_spec, scale,
                           pressure=640., temperature=273.):
    """
    Reproduce the DRP "Correct Dispersion" step (``corrtilt_000.pro``).

    Each wavelength plane of the cube is shifted (bilinearly, zero
    outside the field) by the atmospheric differential refraction
    relative to the first plane; planes needing less than 0.01 lenslet
    in both axes are left untouched, as in ``shift_image.pro``.  The AO
    bench term is off for Keck I data.  For comparisons with DRP cubes
    only.

    Generated by JXP and Claude.

    Args:
        cube (`numpy.ndarray`_):
            Cube (ncols, nrows, nwave) as returned by
            :func:`resample_to_drp_grid` (after the Keck I flip).
        wave (`numpy.ndarray`_):
            Wavelengths (nm).
        elevation (:obj:`float`):
            Telescope elevation (deg, header ``EL``).
        parang (:obj:`float`):
            Parallactic angle (deg, header ``PARANG``).
        pa_spec (:obj:`float`):
            Position angle of the spectrograph (deg, ``PA_SPEC``, or
            ``ROTPOSN - INSTANGL`` if absent, as in the DRP).
        scale (:obj:`float`):
            Lenslet scale (arcsec).
        pressure, temperature (:obj:`float`, optional):
            DRP defaults (640 mbar, 273 K).

    Returns:
        `numpy.ndarray`_: The shifted cube.
    """
    lam = wave / 1e3
    defl = (0.0000744 * (1. + 0.00563 / lam**2)) \
        * np.tan(np.radians(90. - elevation)) / (scale * 1e3) \
        * pressure / temperature * 206265. * 1000.
    defl -= defl[0]
    dx = defl * np.sin(np.radians(pa_spec - parang))
    dy = defl * np.cos(np.radians(pa_spec - parang))
    # DRP: shift along the lenslet rows by -dy and the columns by -dx;
    # the integer parts are zero for these small shifts
    rshift, cshift = -dy, -dx
    out = np.array(cube, dtype=float, copy=True)
    for j in range(wave.size):
        if abs(rshift[j]) < 0.01 and abs(cshift[j]) < 0.01:
            continue
        plane = _shift_axis(cube[:, :, j], rshift[j], 1)
        plane = _shift_axis(plane, cshift[j], 0)
        out[:, :, j] = np.nan_to_num(plane, nan=0.)
    return out
