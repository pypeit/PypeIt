"""
Extraction ("rectification") of interleaved lenslet spectra.

The Keck/OSIRIS lenslet IFU packs up to ~3000 spectra on its 2048 x 2048
detector, two rows apart with a ~2 pixel FWHM, so individual spectra
cannot be traced.  Keck measures the cross-dispersion profile of every
lenslet ("slice") at every detector column and distributes it as a
*rectification matrix* (``sYYMMDD_cNNN___infl_<filter>_<scale>.fits``):

    - ext0 ``hilo`` (nslice, 2): bottom and top detector row of the
      16-row window holding each slice's profile;
    - ext1 ``effective`` (nslice,): 1 if the slice is illuminated;
    - ext2 influence (nslice, 16, 2048): the fraction of the lenslet flux
      landing on row ``hilo[s,0] + l`` of detector column ``x``.

With ``B`` the influence cube and ``b_s`` the bottom row of slice ``s``,
each detector column ``x`` is an independent linear system,

    F[j, x] = sum_s  B[s, j - b_s, x] * c[s, x],

for the lenslet spectra ``c``.  This module provides two solvers:

    - :func:`rectify_drp`: a vectorised, faithful port of the iterative
      solver of the Keck OSIRIS DRP (``spatrectif_000.c``);
    - :func:`rectify_lstsq`: the exact weighted least-squares solution,
      computed band by band (block-tridiagonal normal equations).

Both work in the *raw* detector orientation: the input image has
detector rows along axis 0 and detector columns (dispersion; wavelength
*decreasing* with column for OSIRIS) along axis 1, exactly as stored in
the raw FITS file.  Both return arrays of shape ``(ncol, nslice)``
(i.e. 2048 x 1216): axis 0 is the raw detector column (not flipped) and
axis 1 the slice index.  Following the DRP, the solution is divided by
:data:`DRP_NORM` (1.28).

The module also holds the bookkeeping needed to compare with the DRP
cubes: matrix file selection (:func:`select_matrix`), the narrowband
slice-to-lenslet split (:func:`narrowband_split`) and the resampling to
the DRP wavelength grid (:func:`resample_to_drp_grid`).

Generated by JXP and Claude.

.. include:: ../include/links.rst
"""
