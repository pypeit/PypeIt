def test_sandwich_variance():
    # Flux-independent weights (M2 Q&A 1): the sandwich variance
    # (A^T W A)^-1 A^T W V W A (A^T W A)^-1 matches the scatter of noisy
    # realisations, while diag((A^T W A)^-1) does not.  With W = 1/V both
    # are identical.  Generated by JXP and Claude.
    matrix, spec, img = synthetic_band(line=False)
    rng = np.random.default_rng(7)
    # True variance with a bright "object" in the middle of the band
    var = np.full(img.shape, 4.0)
    var[18:24] += 400.
    wgt = np.full(img.shape, 1 / 4.0)
    _, iv_n, _ = lr.rectify_lstsq(img, 1 / var, None, matrix, norm=1.0,
                                  nband=2)
    _, iv_s, _ = lr.rectify_lstsq(img, 1 / var, None, matrix, norm=1.0,
                                  nband=2, var=var)
    assert np.allclose(iv_s, iv_n, rtol=1e-6)
    sols = []
    for i in range(200):
        noisy = img + rng.normal(size=img.shape) * np.sqrt(var)
        sols.append(lr.rectify_lstsq(noisy, wgt, None, matrix, norm=1.0,
                                     nband=2)[0])
    mc = np.var(np.array(sols), axis=0)
    _, iv_w, _ = lr.rectify_lstsq(img, wgt, None, matrix, norm=1.0,
                                  nband=2, var=var)
    _, iv_wrong, _ = lr.rectify_lstsq(img, wgt, None, matrix, norm=1.0,
                                      nband=2)
    # Spectra overlapping the bright rows
    sel = np.zeros(iv_w.shape, dtype=bool)
    sel[:, 7:12] = True
    assert np.median((mc * iv_w)[sel]) == pytest.approx(1., abs=0.1)
    assert np.median((mc * iv_wrong)[sel]) > 2.
    # lstsq_variance gives the same (normalised) variance without solving
    (v,), vbpm = lr.lstsq_variance(wgt, None, matrix, [var], norm=1.0,
                                   nband=2)
    assert np.allclose(v * iv_w, 1., rtol=1e-6)
    assert not np.any(vbpm)


def test_background_variance():
    # Per-column median background plus the flux-independent variance
    img = np.zeros((50, 4))
    img[:, 1] = 10.
    img[25, 1] = 1e4            # a bright source does not raise the weight
    bvar = lr.background_variance(img, 2.0)
    assert np.allclose(bvar[:, 0], 2.0)
    assert np.allclose(bvar[:, 1], 12.0)


