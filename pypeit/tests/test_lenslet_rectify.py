def test_keck_wavelengths_synthetic():
    # Inversion of a cubic pixel(wavelength) relation
    coeffs = np.array([[1000., -4.5, 1e-4, 1e-7]])
    lam = lr.keck_wavelengths(coeffs, 3)
    x = lr.keck_pixels(lam[0], coeffs[0], 3)
    assert np.max(np.abs(x - np.arange(2048))) < 1e-4
    # Wavelength decreases with column (Keck convention)
    assert np.all(np.diff(lam[0]) < 0)


def test_lenslet_image():
    # Two lenslets sharing slice 0 (narrowband-like) and one in slice 1
    from astropy.table import Table
    lay = Table(dict(slice=[0, 0, 1], pos=[0, 64, 1], xlo=[0, 5, 0],
                     xhi=[4, 9, 9]))
    lay.meta.update(nspat=128)
    rect = np.arange(20, dtype=float).reshape(10, 2)
    img, (ex,), bad = lr.lenslet_image(rect, lay, rect_extra=[2 * rect])
    assert img.shape == (10, 128)
    assert np.array_equal(img[:5, 0], rect[:5, 0])
    assert np.all(img[5:, 0] == 0) and np.all(bad[5:, 0])
    assert np.array_equal(img[5:, 64], rect[5:, 0])
    assert np.array_equal(img[:, 1], rect[:, 1])
    assert np.array_equal(ex, 2 * img)
    assert np.all(bad[:, 2])
