def test_select_matrix(tmp_path):
    for name in ['s160318_c005___infl_Hn3_100.fits',
                 's170101_c001___infl_Hn3_100.fits',
                 's160318_c007___infl_Hn3_100.fits',
                 's160101_c001___infl_Kbb_050.fits',
                 'notes.txt']:
        (tmp_path / name).touch()
    # Latest on or before the date; sequence number breaks the tie
    f = lr.select_matrix(tmp_path, 'Hn3', '0.100', 57468.4)
    assert f.name == 's160318_c007___infl_Hn3_100.fits'
    f = lr.select_matrix(tmp_path, 'Hn3', 0.1, 58000.)
    assert f.name == 's170101_c001___infl_Hn3_100.fits'
    f = lr.select_matrix(tmp_path, 'Kbb', '0.050', 60000.)
    assert f.name == 's160101_c001___infl_Kbb_050.fits'
    # Too early, wrong scale: the error lists what was found
    with pytest.raises(PypeItError, match='s160318_c005'):
        lr.select_matrix(tmp_path, 'Hn3', '0.100', 57000.)
    with pytest.raises(PypeItError):
        lr.select_matrix(tmp_path, 'Hn3', '0.035', 60000.)
    with pytest.raises(PypeItError):
        lr.select_matrix(tmp_path / 'nope', 'Hn3', '0.100', 60000.)


def test_matrix_from_file(tmp_path):
    matrix, _, _ = synthetic_band()
    f = tmp_path / 's160318_c005___infl_Hn3_100.fits'
    hdr = fits.Header({'BASESIZE': 15, 'WTLIMIT': 0.01})
    fits.HDUList([fits.PrimaryHDU(matrix.hilo.astype(np.int16), header=hdr),
                  fits.ImageHDU(matrix.effective.astype(np.int16)),
                  fits.ImageHDU(matrix.influence)]).writeto(f)
    m2 = lr.RectMatrix.from_file(f)
    assert m2.nslice == NSPEC and m2.nwin == 16 and m2.ncol == NCOL
    assert m2.param('BASESIZE') == 15
    assert m2.info['filter'] == 'Hn3'
    assert np.array_equal(m2.bottom, matrix.bottom)


@pytest.mark.parametrize('method', ['drp', 'lstsq'])
def test_synthetic_recovery(method):
    matrix, spec, img = synthetic_band()
    bpm = np.zeros(img.shape, dtype=bool)
    bpm[10, 50] = True
    bpm[21, 77] = True
    for _bpm in [None, bpm]:
        if method == 'drp':
            rect, ivar, rbpm = lr.rectify_drp(img, _bpm, matrix, norm=1.0)
        else:
            rect, ivar, rbpm = lr.rectify_lstsq(img, None, _bpm, matrix,
                                                norm=1.0, nband=1)
        # Output is (ncol, nslice); compare away from the two edge
        # columns (the DRP does not smooth them)
        assert rect.shape == (NCOL, NSPEC)
        frac = np.abs(rect.T / spec - 1)[:, 2:-2]
        assert np.max(frac) < 0.01, f'{method}: {np.max(frac)}'
        assert not np.any(rbpm)


def test_drp_normalisation():
    # The DRP divides the solution by 1.28
    matrix, spec, img = synthetic_band(line=False)
    rect, _, _ = lr.rectify_drp(img, None, matrix)
    assert np.median(rect.T * lr.DRP_NORM / spec) == pytest.approx(1.,
                                                                abs=1e-3)


def test_lstsq_ivar():
    # Propagated variance matches the scatter of noisy realisations
    matrix, spec, img = synthetic_band(line=False)
    rng = np.random.default_rng(42)
    sig = 2.0
    ivar_pix = np.full(img.shape, 1 / sig**2)
    sols = []
    for i in range(100):
        rect, ivar, _ = lr.rectify_lstsq(
            img + rng.normal(0., sig, img.shape), ivar_pix, None, matrix,
            norm=1.0, nband=1)
        sols.append(rect)
    ratio = np.median(np.var(np.array(sols), axis=0) * ivar)
    assert ratio == pytest.approx(1., abs=0.1)


def test_drp_noise_and_mask():
    matrix, spec, img = synthetic_band(line=False)
    noise = np.full(img.shape, 2.)
    # Mask the rows of spectrum 5 at column 100 entirely
    bpm = np.zeros(img.shape, dtype=bool)
    rows = matrix.bottom[5] + np.arange(16)
    bpm[rows[rows < NROW], 100] = True
    rect, ivar, rbpm = lr.rectify_drp(img, bpm, matrix, noise=noise)
    assert rbpm[100, 5]
    assert ivar[100, 5] == 0.
    # DRP rule: sigma_out = sum_l fblame * sigma = 2 away from the mask
    other = np.ones(rbpm.shape, dtype=bool)
    other[100] = False
    assert np.allclose(ivar[other], 0.25, rtol=1e-4)


def test_lstsq_bands():
    # Two bands of 8 spectra; the coupled solution is exact, the
    # independent-band approximation is close but not exact
    matrix, spec, img = synthetic_band(line=False)
    rect, _, _ = lr.rectify_lstsq(img, None, None, matrix, norm=1.0,
                                  nband=2)
    assert np.allclose(rect.T, spec, rtol=1e-5)
    # Adjacent spectra are in different bands with nband=16 (k mod 16),
    # so bands 0 and 2 overlap: not block tridiagonal
    with pytest.raises(PypeItError):
        lr.rectify_lstsq(img, None, None, matrix, nband=16)


def test_narrowband_split():
    bb = lr.narrowband_split('Kbb')
    assert len(bb) == 1216 and bb.meta['broadband']
    assert (bb.meta['nrows'], bb.meta['ncols']) == (64, 19)
    row = bb[bb['slice'] == 70][0]
    assert (row['row'], row['col'], row['crow'], row['ccol']) \
        == (6, 1, 7, 17)
    nb = lr.narrowband_split('Hn3')
    assert not nb.meta['broadband']
    assert (nb.meta['nrows'], nb.meta['ncols']) == (66, 51)
    # 3 blocks of 1024 lenslets plus the sp > 831 extras
    assert len(nb) == 3 * 1024 + (1023 - 831)
    s0 = nb[nb['slice'] == 0]
    assert sorted(zip(s0['row'], s0['col'])) == [(0, 35), (1, 19), (2, 3)]
    s = nb[(nb['slice'] == 900) & (nb['block'] == 3)][0]
    assert (s['row'], s['col']) == (900 % 64 + 3, 900 // 64 - 13)
    # Only the clipped extras (rows 62 and 63 -> 65) land on the same
    # lenslet, once per extra column (as in the DRP, the last one wins)
    pos = list(zip(nb['row'], nb['col']))
    assert len(pos) - len(set(pos)) == 3


