"""
Unit tests for the lenslet rectification solvers (Keck/OSIRIS).

Synthetic data only; the comparison with the Keck DRP reference cube is a
development-suite vet test.

Generated by JXP and Claude.
"""
from pathlib import Path

import numpy as np
import pytest

from astropy.io import fits

from pypeit import PypeItError
from pypeit.core import lenslet_rectify as lr
from pypeit.scripts.osiris_rectify import OsirisRectify


NSPEC = 16          # spectra in the synthetic band
NCOL = 256          # detector columns
MARGIN = 4          # empty rows below and above the 32-row band
NROW = 2 * NSPEC + 2 * MARGIN


def synthetic_band(nspec=NSPEC, ncol=NCOL, margin=MARGIN, fwhm=2.0,
                   amp=0.8, line=True):
    """
    Synthetic 32-row band: 16 spectra 2 rows apart with Gaussian PSFs.

    Generated by JXP and Claude.

    Returns the matrix, the true spectra (nspec, ncol) and the image.
    """
    sig = fwhm / 2.3548
    x = np.arange(ncol)
    # Trace centres with a small sinusoidal wiggle along the dispersion
    cen = margin + 0.5 + 2 * np.arange(nspec)[:, None] \
        + 0.3 * np.sin(2 * np.pi * x / ncol)[None, :]
    bottom = np.floor(cen.mean(axis=1)).astype(int) - 4
    rows = bottom[:, None, None] + np.arange(16)[None, :, None]
    infl = np.exp(-0.5 * ((rows - cen[:, None, :]) / sig)**2)
    infl *= amp / infl.sum(axis=1, keepdims=True)
    infl[infl < 0.01 * amp] = 0.
    hilo = np.stack([bottom, bottom + 15], axis=1)
    matrix = lr.RectMatrix(hilo, np.ones(nspec, dtype=int),
                           infl.astype(np.float32))
    # Known spectra: continuum + per-spectrum offset (+ emission line)
    k = np.arange(nspec)[:, None]
    spec = 100 * (1 + 0.3 * np.sin(2 * np.pi * x[None, :] / 180 + k)) \
        + 5 * k
    if line:
        spec = spec + 200 * np.exp(-0.5 * ((x - 128) / 1.3)**2)[None, :]
    img = np.zeros((2 * nspec + 2 * margin, ncol))
    for s in range(nspec):
        for ll in range(16):
            if bottom[s] + ll < img.shape[0]:
                img[bottom[s] + ll] += infl[s, ll] * spec[s]
    return matrix, spec, img


