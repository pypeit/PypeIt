"""
Unit test of the column-window boxcar extraction of FiberExtract.

Generated by JXP and Claude.
"""
import numpy as np
import pytest

from pypeit.core import extract
from pypeit.extraction import FiberExtract


class _Fiber:
    """Minimal stand-in for a SpecObj (trace and boxcar radius)."""
    def __init__(self, trace, radius):
        self.TRACE_SPAT = trace
        self.BOX_R_PIX = radius


@pytest.mark.parametrize('center,radius', [(10.0, 0.5), (0.0, 0.5),
                                           (119.0, 3.3), (57.3, 2.7)])
def test_window_boxcar(center, radius):
    # Extracting from the column window around the aperture gives the same
    # result as the full image (FiberExtract speed-up)
    rng = np.random.default_rng(1)
    nspec, nspat = 200, 120
    img = rng.normal(size=(nspec, nspat))
    ivar = np.full(img.shape, 2.)
    mask = rng.random(img.shape) > 0.05
    wave = np.tile(np.linspace(1e4, 2e4, nspec)[:, None], (1, nspat))
    sky = rng.random(img.shape)
    bvar = np.ones(img.shape)
    trace = center + 0.4 * np.sin(np.arange(nspec) / 20.) \
        if 0 < center < nspat - 1 else np.full(nspec, center)
    full = extract.extract_boxcar(radius, trace, img, ivar, mask, wave, sky,
                                  base_var=bvar, noise_floor=0.01)
    x0, x1 = FiberExtract._fiber_columns(_Fiber(trace, radius), nspat)
    c = slice(x0, x1)
    crop = extract.extract_boxcar(radius, trace - x0, img[:, c], ivar[:, c],
                                  mask[:, c], wave[:, c], sky[:, c],
                                  base_var=FiberExtract._crop(bvar, c),
                                  noise_floor=0.01)
    for a, b in zip(full, crop):
        if a is not None:
            assert np.allclose(a, b, equal_nan=True)
    assert FiberExtract._crop(None, c) is None
