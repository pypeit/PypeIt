def test_oh_line_residuals():
    # Integrated residual of lines that are 10 % stronger in A than in B
    disp = 2.5
    pix = np.arange(NSPEC, dtype=float)
    wave = 19700. + disp * pix[:, None] + np.zeros((1, NFIB))
    lw = np.linspace(19900., 22200., 12)
    x = 500. * line_spectra(wave, lw, np.ones(lw.size))
    y = 0.1 * x
    gpm = np.ones_like(x, dtype=bool)
    ppos = np.zeros(NFIB, dtype=int)
    sx, sy0, sy1 = skysub.oh_line_residuals(wave, y, x, 0.1 * x, gpm, lw,
                                            ppos, 1)
    assert np.allclose(sy0 / sx, 0.1)
    assert np.allclose(sy1, 0., atol=1e-8)
    # Windows with a masked pixel are skipped
    gpm[:, :10] = False
    sx2, _, _ = skysub.oh_line_residuals(wave, y, x, 0.1 * x, gpm, lw,
                                         ppos, 1)
    assert np.allclose(sx2, 0.75 * sx)


def test_oh_scaling_guard():
    # The A lines are narrower than the B lines (same flux): the pixel fit
    # finds a positive factor that lowers the pixel rms but creates an
    # integrated residual; the integrated guard rejects it, the M4 'rms'
    # guard does not
    disp = 2.5
    pix = np.arange(NSPEC, dtype=float)
    wave = 19700. + disp * pix[:, None] + 0.3 * np.arange(NFIB)[None, :]
    lw = np.linspace(20000., 22300., 25)
    cont = 100.
    b = cont + 800. * line_spectra(wave, lw, np.ones(lw.size), fwhm_pix=2.6)
    # Same line flux: the peak scales inversely with the FWHM
    a = cont + 800. * 2.6 / 2.0 * line_spectra(wave, lw, np.ones(lw.size),
                                               fwhm_pix=2.0)
    rng = np.random.default_rng(7)
    a = a + rng.normal(0., 2., a.shape)
    b = b + rng.normal(0., 2., b.shape)
    resid = a - b
    ivar = np.full(resid.shape, 1. / 8.)
    gpm = np.ones_like(resid, dtype=bool)
    pool = np.zeros(NFIB, dtype=int)
    names = skysub.OH_GROUP_NAMES
    g = names.index('8-6')
    _, sc_rms, _, _, st_rms = skysub.oh_scaled_sky(
        wave, resid, ivar, b, gpm, pool, line_wave=lw, guard='rms')
    _, sc_int, _, _, st_int = skysub.oh_scaled_sky(
        wave, resid, ivar, b, gpm, pool, line_wave=lw, guard='integrated')
    assert sc_rms[0, g] > 0.02
    assert st_rms['int_after'] > st_rms['int_before']
    assert np.all(sc_int == 0.)
    assert st_int['int_after'] == pytest.approx(st_int['int_before'])


def test_fiber_cosmic_rays():
    # Smooth spectra with a real emission line shared by all fibers (and
    # an absorption line in a bright fiber), plus positive and negative
    # single-fiber spikes: only the spikes are flagged
    disp = 2.5
    pix = np.arange(NSPEC, dtype=float)
    # Staggered wavelengths, as for OSIRIS lenslets in a block
    wave = 19700. + disp * (pix[:, None] - 1.9 * np.arange(NFIB)[None, :])
    bright = 1. + 4. * (np.arange(NFIB) == 20)
    cont = 200. * bright[None, :] * np.ones_like(wave)
    line = 300. * line_spectra(wave, [21000.], [1.]) \
        - 60. * bright[None, :] * line_spectra(wave, [21500.], [1.])
    rng = np.random.default_rng(3)
    flux = cont + line + rng.normal(0., 5., wave.shape)
    ivar = np.full(wave.shape, 1. / 25.)
    gpm = np.ones_like(flux, dtype=bool)
    hits = [(300, 5, 400.), (301, 5, 150.), (700, 12, -300.), (900, 33, 90.)]
    for i, k, v in hits:
        flux[i, k] += v
    nfib = NFIB
    nb = np.full((nfib, 4), -1, dtype=int)
    for i, d in enumerate((-2, -1, 1, 2)):
        j = np.arange(nfib) + d
        ok = (j >= 0) & (j < nfib)
        nb[ok, i] = j[ok]
    cr = skysub.fiber_cosmic_rays(flux, ivar, gpm, wave, nb, nsig=8.)
    for i, k, _ in hits:
        assert cr[i, k]
    # Nothing else: not the emission line, not the absorption line of the
    # bright fiber
    expected = np.zeros_like(cr)
    for i, k, _ in hits:
        expected[i, k] = True
    assert np.array_equal(cr, expected)
