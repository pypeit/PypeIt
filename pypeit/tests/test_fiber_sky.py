"""
Unit tests of the generic Fiber-pypeline sky tools added for Keck/OSIRIS
(milestone M4): per-fiber sky-line refinement of the wavelengths and the
Davies (2007) OH-line scaling.  Synthetic data only.

Generated by JXP and Claude.
"""
import numpy as np
import pytest

from astropy.table import Table

from pypeit.core import skysub
from pypeit.core.wavecal import wvutils


NSPEC = 1024
NFIB = 40
RNG = np.random.default_rng(42)
# Isolated "OH" lines (Angstrom) and a blend pair (second component flagged)
LINES = Table(dict(wave=[20100., 20400., 20700., 21000., 21300., 21600.,
                         21900., 22200., 22500., 22200. + 4.],
                   amplitude=[1., 1., 0.8, 1., 0.6, 1., 0.9, 1., 0.7, 0.],
                   NIST=[1, 1, 1, 1, 1, 1, 1, 1, 1, 0]))


def line_spectra(waves, line_wave, amp, fwhm_pix=2.0, disp=2.5):
    """Gaussian lines on the given wavelength grids (nspec, nfib)."""
    sig = fwhm_pix / 2.3548 * disp
    out = np.zeros_like(waves)
    for w, a in zip(line_wave, amp):
        out += a * np.exp(-0.5 * ((waves - w) / sig)**2)
    return out


def test_isolated_lines():
    lw = wvutils.isolated_lines(LINES['wave'], 15.,
                                line_ok=np.asarray(LINES['NIST']) > 0)
    # 22200 has a blend component 4 A away: rejected; the blend itself is
    # never used
    assert 22200. not in lw and 22204. not in lw
    assert lw.size == 8


@pytest.mark.parametrize('mode', ['zeropoint', 'block'])
def test_fiber_sky_refinement(mode):
    # Fibers whose true lines are shifted by known pixel offsets relative
    # to their nominal solution (a common zero point plus a trend with the
    # spatial position) are recovered to < 0.02 px
    disp = 2.5
    pix = np.arange(NSPEC, dtype=float)
    true_shift = 0.5 + 0.004 * np.arange(NFIB)
    nominal = 19900. + disp * pix[:, None] + np.zeros((1, NFIB))
    # True wavelength at pixel x is nominal(x - shift)
    true_wave = nominal - true_shift[None, :] * disp
    spec = 1000. * line_spectra(true_wave, LINES['wave'],
                                LINES['amplitude'].data + 0.05) + 50.
    spec += RNG.normal(0., 3., spec.shape)
    gpm = np.ones_like(spec, dtype=bool)
    spat = np.arange(NFIB, dtype=float)
    block = np.zeros(NFIB, dtype=int)
    applied, shift, err, nline, info = wvutils.fiber_sky_refinement(
        spec, nominal, gpm, LINES, fwhm=2.0, mode=mode, spat=spat,
        block=block)
    assert info['nlines_list'] == 8
    assert np.all(nline >= 6)
    assert np.max(np.abs(applied - true_shift)) < 0.02
    # Faint fibers: no individual measurement, the stack gives the common
    # zero point
    faint = 2. * line_spectra(true_wave, LINES['wave'],
                              LINES['amplitude'].data + 0.05) \
        + RNG.normal(0., 1., spec.shape)
    applied, shift, _, _, info = wvutils.fiber_sky_refinement(
        faint, nominal, gpm, LINES, fwhm=2.0)
    assert np.all(np.isnan(shift)) and info['fill_from'] == 'stack'
    assert abs(applied[0] - np.mean(true_shift)) < 0.1


def test_oh_scaled_sky():
    # Sky lines of two Davies groups vary by +6 % and -3 % between the
    # object and sky frames; a cosmic ray in the sky frame is ignored
    disp = 2.5
    pix = np.arange(NSPEC, dtype=float)
    wave = 19700. + disp * pix[:, None] + 0.3 * np.arange(NFIB)[None, :]
    lw = np.linspace(19800., 22400., 30)
    sky_lines = 800. * line_spectra(wave, lw, np.ones(lw.size))
    cont = 100. + 0.01 * (wave - 19700.)
    s = np.where(wave < 20950., 0.06, -0.03)
    obj = 50. * np.exp(-0.5 * ((np.arange(NFIB) - 20) / 5.)**2)[None, :] \
        * (1 + 0.1 * np.sin(wave / 300.))
    sky = cont + sky_lines + RNG.normal(0., 3., wave.shape)
    a = cont + (1 + s) * sky_lines + obj + RNG.normal(0., 3., wave.shape)
    sky[500, 7] += 3e4
    resid = a - sky
    ivar = np.full(resid.shape, 1. / 18.)
    gpm = np.ones_like(resid, dtype=bool)
    model, scales, npix, pools, stats = skysub.oh_scaled_sky(
        wave, resid, ivar, sky, gpm, np.zeros(NFIB, dtype=int))
    names = skysub.OH_GROUP_NAMES
    assert np.isclose(scales[0, names.index('8-6')], 0.06, atol=0.005)
    assert np.isclose(scales[0, names.index('9-7')], -0.03, atol=0.005)
    assert stats['line_rms_after'] < 0.3 * stats['line_rms_before']
    # Per-fiber pooling gives the same factors, noisier
    _, sc_f, _, pools_f, _ = skysub.oh_scaled_sky(
        wave, resid, ivar, sky, gpm, np.arange(NFIB))
    assert pools_f.size == NFIB
    assert np.isclose(np.median(sc_f[:, names.index('8-6')]), 0.06,
                      atol=0.01)
    # No variation: no (significant) correction
    _, sc0, _, _, _ = skysub.oh_scaled_sky(
        wave, (cont + sky_lines + RNG.normal(0., 3., wave.shape)) - sky,
        ivar, sky, gpm, np.zeros(NFIB, dtype=int))
    assert np.all(np.abs(sc0) < 0.01)
